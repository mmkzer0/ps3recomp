def main() -> None:
    p = argparse.ArgumentParser(description="SPU to C lifter for ps3recomp")
    p.add_argument("input", nargs="?", default=None,
                   help="Raw SPU binary (local-store image) or segment. "
                        "Omit if --auto-functions is set.")
    p.add_argument("--output", "-o", default=".", help="Output directory")
    p.add_argument("--header-name", default="spu_recomp.h")
    p.add_argument("--source-name", default="spu_recomp.c")
    p.add_argument("--base", type=lambda x: int(x, 0), default=0,
                   help="Base local-store address")
    p.add_argument("--link-base", type=lambda x: int(x, 0), default=None,
                   help="Linked image base for the return-proof entry veto inventory only; "
                        "omitted means no relocation, explicit 0 means linked at zero.")
    p.add_argument("--offset", type=lambda x: int(x, 0), default=0)
    p.add_argument("--length", type=lambda x: int(x, 0), default=0)
    p.add_argument("--functions", metavar="FILE",
                   help="JSON list [{\"start\":addr,\"end\":addr}, ...]")
    p.add_argument("--auto-functions", metavar="ELF",
                   help="Auto-detect function boundaries from the given SPU "
                        "ELF using find_spu_functions.py (entry + brsl/brasl "
                        "targets + STT_FUNC symbols). When set, .text is "
                        "read from this ELF and the positional <input> arg "
                        "is ignored.")
    p.add_argument("--report", help="Write machine-readable generation diagnostics JSON")
    p.add_argument("--trace", action="store_true",
                   help="Emit spu_trace_pc/spu_trace_rt around each instruction "
                        "for §3 diff-vs-RPCS3 validation. Output goes to stderr "
                        "unless spu_trace_init(path) is called by the harness.")
    p.add_argument("--symbol-prefix", default="",
                   help="Prefix for all emitted spu_func_* / spu_recomp_register "
                        "symbols, so multiple lifted SPU images can link into one "
                        "binary without colliding (e.g. flow_spu_00_). Default: none.")
    p.add_argument("--extra-funcs", default="",
                   help="Comma-separated extra function entry addresses (e.g. "
                        "0x10F8,0x808) to add as boundaries -- for indirect-branch "
                        "targets that --auto-functions can't detect statically. "
                        "Splits the containing auto-detected function at each addr.")
    p.add_argument("--override", action="append", default=[], metavar="ADDR=SYMBOL",
                   help="Replace a decoded leaf function's references with a native "
                        "void SYMBOL(spu_context*) supplied by the consumer. Repeatable.")
    p.add_argument("--return-entries", action="store_true",
                   help="Also make the return address of every call (brsl, "
                        "brasl, bisl, bisled) an entry point. Code that is "
                        "resumed rather than returned to needs it: a SPURS task "
                        "calls the policy module's syscall entry, the policy "
                        "saves the task and exits to the kernel (abandoning the "
                        "host frames), and later resumes the task by branching "
                        "to that return address. Splits existing functions only "
                        "(never seeds a gap), and the splits do not start new "
                        "--merge-chunks groups, so straight-line speed is kept.")
    p.add_argument("--code-end", type=lambda x: int(x, 0), default=0,
                   help="Address where executable code ends and an embedded "
                        "rodata/const tail begins. Drops any auto-detected "
                        "function starting at/after this address and caps any "
                        "function's end here, so the data tail is left "
                        "un-disassembled. For images with a large data tail in "
                        ".text whose bytes decode as in-range branches and seed "
                        "garbage `functions` (e.g. the LBP WWS physics jobmods, "
                        "which append a zlib inflate string table + float tables "
                        "after the code at 0xAE68 / 0xAE48).")
    p.add_argument("--merge-chunks", action="store_true",
                   help="Emit each run of contiguous chunks from one call target "
                        "to the next as ONE C function (branches between them "
                        "become gotos) instead of one function per chunk linked "
                        "by trampolines. Every chunk is still emitted and "
                        "registered on its own for indirect entry, so this only "
                        "changes speed, not which code can be reached.")
    p.add_argument("--reloc", action="store_true",
                   help="Position-independent code the title places at a different LS "
                        "address per load: lift once at --base, and offset every "
                        "pc-derived address by ctx->reloc_delta at run time (register "
                        "with spu_overlay_register_region_reloc).")
    p.add_argument("--max-group-insns", type=int, default=4000,
                   help="Cap on instructions per merged group (keeps clang fast).")
    p.add_argument("--force-indirect", default="",
                   help="Comma-separated `bi $rN` addresses to emit as GENERIC "
                        "indirect dispatch, overriding the link-register-return "
                        "classifier. For jump-table dispatches whose target reg "
                        "was computed in a block the bounded liveness scan cannot "
                        "see (e.g. pm_wwsjob 0x2E74: r6 loaded from the command "
                        "dispatch table at 0x1BD8, `br` into a fallthrough chain, "
                        "dispatched blocks later -- classified as a return, which "
                        "silently skipped every job-command handler).")
    args = p.parse_args()
    try:
        overrides = parse_overrides(args.override)
    except ValueError as error:
        p.error(str(error))

    independent_entries = set()
    if args.auto_functions:
        from find_spu_functions import detect_functions, parse_elf, pick_text, text_image
        with open(args.auto_functions, "rb") as f:
            elf_buf = f.read()
        funcs, (text_off, base, size) = detect_functions(elf_buf)
        data, _ = text_image(elf_buf, parse_elf(elf_buf)["phs"])
        if args.base != 0:
            base = args.base  # caller override
        bounds = funcs
        from find_spu_functions import read_symbols
        elf_info = parse_elf(elf_buf)
        independent_entries.add(elf_info["entry"])
        independent_entries.update(symbol["addr"]
                                   for symbol in read_symbols(elf_buf, elf_info["shs"]))
    else:
        with open(args.input, "rb") as f:
            data = f.read()
        # An ELF handed in as the positional input is read as a RAW image: the
        # ELF header becomes the first instructions and every address is a file
        # offset, so a lifted "func_00000100" is really the code at LS
        # (0x100 - p_vaddr + p_offset). It compiles, links and runs -- straight
        # into the wrong instructions -- which is an expensive way to find a
        # missing flag. Use --auto-functions for an ELF, or say --offset/--base
        # explicitly if the raw read is deliberate.
        if data[:4] == b"ELF" and args.offset == 0 and args.base == 0:
            p.error("input is an ELF but no --auto-functions/--offset/--base was "
                    "given: it would be lifted as a raw image at base 0, placing "
                    "every function at its FILE OFFSET instead of its local-store "
                    "address. Pass --auto-functions <same elf> to lift it as an "
                    "ELF, or --offset/--base to confirm a raw read.")
        data = data[args.offset:]
        if args.length:
            data = data[:args.length]
        base = args.base

        if args.functions:
            with open(args.functions) as f:
                flist = json.load(f)
            bounds = [(int(str(e["start"]), 0), int(str(e["end"]), 0))
                      for e in flist]
        else:
            # No boundary info: treat the whole image as one function.
            bounds = [(base, base + len(data))]

    from find_spu_functions import image_delta
    insns = disassemble_spu(data, base)
    # Call return addresses as entries (--return-entries): split the bound that
    # contains each one. Not merge-group seeds -- see the option's help.
    if args.return_entries:
        hi = args.code_end or (base + len(data))
        getters = set()
        if bounds:
            *_, getters = _r0_link_entry_inventory(
                insns, bounds, data, base, image_delta(base, args.link_base),
                [base, *independent_entries])
        rets = sorted({i.addr + 4 for i in insns
                       if i.mnemonic in ("brsl", "brasl", "bisl", "bisled")
                       and i.addr not in getters and i.addr + 4 < hi})
        newb = []
        for (s0, e0) in sorted(set(bounds)):
            cuts = [a for a in rets if s0 < a < e0]
            prev = s0
            for a in cuts:
                newb.append((prev, a)); prev = a
            newb.append((prev, e0))
        by_start = {}
        for s0, e0 in newb:
            if s0 not in by_start or e0 < by_start[s0]:
                by_start[s0] = e0
        sys.stderr.write("[spu_lifter] return entries: %d call return address(es), %d -> %d bound(s)\n"
                         % (len(rets), len(bounds), len(by_start)))
        bounds = sorted(by_start.items())

    # Add extra function entry points (indirect-branch targets auto-detect misses)
    # by splitting whichever bound contains each address.
    if args.extra_funcs:
        extra = [int(x, 0) for x in args.extra_funcs.split(",") if x.strip()]
        bset = sorted(set(bounds))
        for a in extra:
            newb = []
            split = False
            for (s, e) in bset:
                if s < a < e:
                    newb.append((s, a)); newb.append((a, e)); split = True
                else:
                    newb.append((s, e))
            if not split and not any(s == a for s, _ in bset):
                # A seed in a gap between bounds (or past the last one) runs to
                # the next function start, not the image end: otherwise a
                # 2-instruction stub swallows every function after it and any
                # rodata tail (hundreds of `.word` unsupported).
                nxt = min([s for s, _ in bset if s > a] + [base + len(data)])
                newb.append((a, nxt))

            bset = sorted(set(newb))
        # Dedup by start: if an extra addr lands inside two overlapping auto-
        # detected bounds, splitting both yields two bounds with the same start
        # -> two functions emitted with the same name (redefinition). Keep one
        # per start (the tightest end); the start is what dispatch resolves to.
        by_start = {}
        for s, e in bset:
            if s not in by_start or e < by_start[s]:
                by_start[s] = e
        bounds = sorted(by_start.items())
        sys.stderr.write("[spu_lifter] added extra funcs: %s\n" %
                         ", ".join("0x%X" % a for a in extra))

    # Cap the code/data boundary. Some images embed a large rodata/const tail
    # inside the executable segment; its bytes decode as in-range branches
    # (br/brsl/brhz ...) whose targets seed spurious "functions", which then
    # disassemble the data as code (garbage + `.word` for undecodable words).
    # Reachability from the entry can't bound it (the entry is an indirect
    # dispatch stub), so the boundary is supplied explicitly per image.
    if args.code_end:
        ce = args.code_end
        before = len(bounds)
        bounds = [(s, min(e, ce)) for (s, e) in bounds if s < ce]
        sys.stderr.write("[spu_lifter] code-end 0x%X: kept %d/%d bound(s), "
                         "data tail left un-disassembled\n"
                         % (ce, len(bounds), before))


    lifter = SPULifter(trace=args.trace, prefix=args.symbol_prefix, overrides=overrides)
    independent_entries.add(base)
    if args.extra_funcs:
        independent_entries.update(int(value, 0) for value in args.extra_funcs.split(",")
                                   if value.strip())
    lifter.bi_r0_jump = compute_bi_r0_jumps(
        insns, bounds, image=data, base=base, delta=image_delta(base, args.link_base),
        entry_points=independent_entries)
    if lifter.bi_r0_jump:
        print(f"  {len(lifter.bi_r0_jump)} `bi $r0` computed-jump site(s) "
              f"(not proven caller links): "
              f"{', '.join(f'0x{a:X}' for a in sorted(lifter.bi_r0_jump))}")
    if lifter.bi_r0_jump.link_restores:
        for site, load in sorted(lifter.bi_r0_jump.link_restores.items()):
            assumptions = json.dumps(lifter.bi_r0_jump.return_assumptions[site])
            print(f"  `bi $r0` return 0x{site:X} (lqd 0x{load:X}): "
                  f"assumes={assumptions}")
    lifter.link_return = compute_link_returns(insns, bounds)
    if args.force_indirect:
        forced = {int(x, 0) for x in args.force_indirect.split(",") if x.strip()}
        dropped = lifter.link_return & forced
        lifter.link_return -= forced
        lifter.bi_r0_jump |= forced
        lifter.bi_r0_jump.link_restores = {
            site: load for site, load in lifter.bi_r0_jump.link_restores.items()
            if site not in forced
        }
        lifter.bi_r0_jump.assumes = (
            "spu-abi-link-slot" if lifter.bi_r0_jump.link_restores else None)
        lifter.bi_r0_jump.inherited_returns -= forced
        lifter.bi_r0_jump.callee_saved_returns -= forced
        lifter.bi_r0_jump.private_slot_returns -= forced
        lifter.bi_r0_jump.unresolved_branches |= forced
        lifter.bi_r0_jump.return_assumptions = {
            site: lifter.bi_r0_jump.assumptions_for(site)
            for site in lifter.bi_r0_jump.link_restores
        }
        sys.stderr.write("[spu_lifter] forced indirect dispatch at: %s%s\n" %
                         (", ".join("0x%X" % a for a in sorted(forced)),
                          " (was link-return: %s)" %
                          ", ".join("0x%X" % a for a in sorted(dropped))
                          if dropped else ""))
    if lifter.link_return:
        print(f"  {len(lifter.link_return)} non-r0 link-register return site(s) "
              f"(`bi $rN` where rN is a brsl/bisl link reg): "
              f"{', '.join(f'0x{a:X}' for a in sorted(lifter.link_return))}")
    lifter.func_starts = {s for s, e in bounds}  # for fall-through tail-call chaining
    groups = {}
    if args.merge_chunks:
        seeds = {base}
        if args.extra_funcs:
            seeds |= {int(x, 0) for x in args.extra_funcs.split(",") if x.strip()}
        groups = merge_chunk_groups(insns, bounds, args.max_group_insns,
                                    entry_points=seeds)
        print(f"  {len(groups)} merged function group(s) "
              f"(--merge-chunks, max {args.max_group_insns} insns)")
    if overrides:
        ends = dict(bounds)
        if set(overrides) - set(ends):
            missing = min(set(overrides) - set(ends))
            p.error(f"--override 0x{missing:X} is not a decoded function entry")
        generated = {f"{lifter.prefix}spu_func_{start:08X}" for start, _ in bounds}
        generated.add(f"{lifter.prefix}spu_recomp_register")
        generated.update(f"{lifter.prefix}spu_func_{target:08X}"
                         for target in lifter.call_targets | lifter.branch_targets)
        for address, symbol in overrides.items():
            if symbol in generated:
                p.error(f"--override 0x{address:X} symbol {symbol!r} conflicts with a lifted symbol")
            end = groups.get(address, ends[address])
            problem = override_leaf_problem(insns, address, end, lifter.bi_r0_jump,
                                            lifter.func_starts)
            if problem:
                p.error(f"--override 0x{address:X} refuses non-leaf function: {problem}")

    for s, e in bounds:
        lifter.lift_function(insns, s, groups.get(s, e))

    os.makedirs(args.output, exist_ok=True)
    hp = os.path.join(args.output, args.header_name)
    sp = os.path.join(args.output, args.source_name)
    with open(hp, "w") as f:
        f.write(lifter.emit_header())
    with open(sp, "w") as f:
        f.write(lifter.emit_source(args.header_name))

    if args.report:
        with open(args.report, "w", encoding="utf-8") as report:
            json.dump({"functions": [[f.start_addr, f.end_addr] for f in lifter.functions],
                       "unsupported": lifter.unsupported,
                       "call_targets": sorted(lifter.call_targets),
                       "branch_targets": sorted(lifter.branch_targets),
                       "r0_returns": [
                           {"site": site, "load": load,
                            "inherited": site in lifter.bi_r0_jump.inherited_returns,
                            "assumes": lifter.bi_r0_jump.return_assumptions[site]}
                           for site, load in sorted(lifter.bi_r0_jump.link_restores.items())
                       ],
                       "unresolved_register_branches": sorted(
                           lifter.bi_r0_jump.unresolved_branches),
                       "r0_dispatches": [
                           {"site": site, "reason": lifter.bi_r0_jump.unproven.get(
                               site, "unproven-target")}
                           for site in sorted(lifter.bi_r0_jump)
                       ]}, report, indent=2)

    print(f"Wrote {hp}")
    print(f"Wrote {sp}")
    print(f"  {len(lifter.functions)} function(s) lifted")
    print(f"  {len(lifter.call_targets)} call target(s)")
    if lifter.unsupported:
        total = sum(lifter.unsupported.values())
        print(f"  {total} unsupported instruction(s) across "
              f"{len(lifter.unsupported)} mnemonic(s):")
        for mn, n in sorted(lifter.unsupported.items(), key=lambda kv: -kv[1]):
            print(f"      {mn:<10s} {n}")


if __name__ == "__main__":
    main()
