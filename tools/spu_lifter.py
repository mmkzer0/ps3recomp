# Mnemonics whose last operand is a branch target address (0x...).
_COND_BR = {"brz", "brnz", "brhz", "brhnz"}


# Mnemonics that do NOT write the rt register (so we skip the post-trace).
# Everything else writes rt = ops[0] (= insn.raw & 0x7F).
_NO_RT_WRITE = {
    "stop", "stopd", "lnop", "nop", "sync", "syncc", "dsync",
    "bi", "iret", "biz", "binz", "bihz", "bihnz",
    "br", "bra", "brz", "brnz", "brhz", "brhnz",
    "hbr", "hbra", "hbrr",
    "stqd", "stqa", "stqr", "stqx",
    "wrch",
    "hgt", "hlgt", "heq", "hgti", "hlgti", "heqi",
}


def _bi_target_reg(insn):
    """Return the branch-target register of a bi/biz/binz/... insn, or None."""
    ops = _ops(insn.operands)
    if insn.mnemonic == "bi" and ops:
        return _reg(ops[0])
    if insn.mnemonic in ("biz", "binz", "bihz", "bihnz") and len(ops) >= 2:
        return _reg(ops[1])
    return None


# RRR (4-operand) SPU ops write their destination in bits 21-27; the low 7 bits
# (raw & 0x7F) are the RC *source* for these. Every other format writes bits 0-6.
_RRR_DEST_OPS = {"selb", "shufb", "mpya", "fnms", "fma", "fms"}

def _dest_reg(insn) -> int:
    """The register an instruction writes (rt), accounting for RRR-format ops
    whose destination is bits 21-27 rather than the low 7 bits."""
    if insn.mnemonic in _RRR_DEST_OPS:
        return (insn.raw >> 21) & 0x7F
    return insn.raw & 0x7F

def _writes_r0(insn) -> bool:
    return insn.mnemonic not in _NO_RT_WRITE and _dest_reg(insn) == 0


class BiR0Classification(set):
    """Computed bi-r0 dispatches plus return sites relying on the SPU ABI."""

    def __init__(self, jumps=(), link_restores=()):
        super().__init__(jumps)
        self.link_restores = dict(link_restores)
        self.assumes = "spu-abi-link-slot" if self.link_restores else None
        self.inherited_returns = set()
        self.callee_saved_returns = set()
        self.private_slot_returns = set()
        self.unresolved_branches = set()
        self.link_returns = set()
        self.pc_getters = set()
        self.return_assumptions = {}
        self.unproven = {}

    def assumptions_for(self, site):
        assumptions = []
        if site in self.inherited_returns and self.unresolved_branches:
            assumptions.append("no-unmodelled-indirect-entry")
        if site in self.callee_saved_returns:
            assumptions.append("spu-abi-callee-saved")
        assumptions.append("spu-abi-link-slot")
        if site in self.private_slot_returns:
            assumptions.append("spu-abi-link-slot-private")
        return assumptions[0] if len(assumptions) == 1 else assumptions


def _stack_link_load_offset(insn):
    if insn.mnemonic != "lqd":
        return None
    ops = _ops(insn.operands)
    if len(ops) != 2 or _reg(ops[0]) != "0":
        return None
    offset, base = _disp_base(ops[1])
    if base != "1":
        return None
    try:
        return int(offset, 0)
    except (TypeError, ValueError):
        return None


def _parse_imm_int(token):
    try:
        return int(token, 0)
    except ValueError:
        return None


def _r0_link_entry_inventory(insns, bounds, image, base, delta, entry_points):
    """Known non-direct entries veto inheritance; exact dispatches share the pipeline evaluator."""
    from find_spu_functions import (
        collect_branch_targets,
        collect_computed_branch_targets,
        collect_duff_targets,
        collect_ila_continuation_targets,
        collect_jump_table_targets,
        immediate_ls_addresses,
    )

    # Deferred: the pipeline imports this module's option parser. Sharing its
    # exact evaluator keeps a resolved dispatch from becoming two conventions.
    from spu_program_pipeline import _dispatch_targets, _pc_getter

    starts = {s for s, _ in bounds}
    low, high = min(starts), max(e for _, e in bounds)
    independent = set(entry_points)
    independent.update(collect_ila_continuation_targets(insns, low, high, delta))
    independent.update(collect_computed_branch_targets(insns))
    independent.update(collect_duff_targets(insns, low, high))
    independent.update(collect_jump_table_targets(insns, image, base, base + len(image),
                                                  delta=delta))
    for offset in range(0, len(image) - 3, 4):
        independent.update(immediate_ls_addresses(
            int.from_bytes(image[offset:offset + 4], "big"), delta))
    active = {address for start, end in bounds for address in range(start, end, 4)}
    continuations = {}
    call_links = {}  # entry -> bitset of link registers used by known call edges
    direct_getters = {insn.addr for insn in insns if _pc_getter(insn)}
    for insn in insns:
        if insn.addr in direct_getters:
            continue
        if insn.mnemonic in ("brsl", "brasl", "bisl", "bisled"):
            target = SPULifter._branch_target(insn)
            if target is not None:
                independent.add(target)
                if insn.addr in active:
                    call_links[target] = call_links.get(target, 0) | (1 << (insn.raw & 0x7F))
            if insn.addr + 4 in starts:
                if insn.addr in active and insn.mnemonic in ("brsl", "bisl"):
                    continuations[insn.addr + 4] = insn.addr
                else:
                    independent.add(insn.addr + 4)
        elif insn.addr not in active:
            target = SPULifter._branch_target(insn)
            if target is not None:
                independent.add(target)

    getter_targets = {insn.addr + 4 for insn in insns if insn.addr in direct_getters}
    cuts = ((starts - getter_targets) | independent
            | collect_branch_targets([insn for insn in insns if insn.addr not in direct_getters]))
    addresses = {insn.addr for insn in insns}
    while True:
        resolved = {}
        discovered = set()
        pc_getters = set(direct_getters)
        for i, insn in enumerate(insns):
            if _bi_target_reg(insn) is not None or insn.mnemonic in ("bisl", "bisled"):
                targets = _dispatch_targets(
                    insns, i, cuts, addresses.__contains__,
                    register=(insn.raw >> 7) & 0x7F)
                if targets:
                    resolved[insn.addr] = targets
                    if _pc_getter(insn, targets):
                        pc_getters.add(insn.addr)
                    else:
                        discovered.update(targets)
        independent.update(discovered)
        if discovered <= cuts:
            for insn in insns:
                if insn.addr in pc_getters:
                    continuations.pop(insn.addr + 4, None)
                    continue
                if insn.addr in active and insn.mnemonic in ("bisl", "bisled"):
                    for target in resolved.get(insn.addr, ()):
                        call_links[target] = call_links.get(target, 0) | (
                            1 << (insn.raw & 0x7F))
            return independent, resolved, continuations, call_links, pc_getters
        cuts.update(discovered)


@dataclass(frozen=True)
class _LinkState:
    sp_delta: int | None
    live_link: bool
    slots: frozenset
    inherited: bool = False
    callee_saved: bool = False
    stack_derived: int = 1 << 1
    private_slots: frozenset = frozenset()
    live_link_private: bool = False


def _stack_derived_after(insn, derived):
    """May-provenance: joins union it, so any stack-derived address stays a veto."""
    if insn.mnemonic in _NO_RT_WRITE:
        return derived
    destination = _dest_reg(insn)
    bit = 1 << destination
    mn = insn.mnemonic
    if mn in ("lqd", "lqx", "lqa", "lqr", "il", "ila", "ilh", "ilhu",
              "fsmbi", "rdch", "rchcnt", "mfspr", "brsl", "brasl", "bisl", "bisled"):
        value = False
    else:
        sources = re.findall(r"\$r(\d+)", ",".join(_ops(insn.operands)[1:]))
        value = any(derived & (1 << int(reg)) for reg in sources)
        if mn not in ("ori", "ai", "a", "sf", "sfi", "or"):
            # Unmodelled arithmetic may read its old destination implicitly.
            value = value or bool(derived & bit)
    return ((derived | bit) if value else (derived & ~bit)) | (1 << 1)


def _r0_link_restore_loads(insns, bounds, independent, continuations, call_links, pc_getters):
    """Product-lattice must-save proof across direct and ABI-continuation edges."""
    # A merged report may overlap its constituent chunks. The most specific
    # start owns an instruction; inheritance still crosses every split start.
    owner = {}
    for start, end in sorted(bounds):
        for address in range(start, end, 4):
            owner[address] = start
    fn = [insn for insn in insns if insn.addr in owner]
    if not fn:
        return set(), set(), set(), set(), {}
    index = {insn.addr: i for i, insn in enumerate(fn)}
    starts = {s for s, _ in bounds}
    opaque_owners = set()
    after_opaque = set()
    for insn in fn:
        if owner[insn.addr] in opaque_owners:
            after_opaque.add(insn.addr)
        if _bi_target_reg(insn) is not None or insn.mnemonic == "iret":
            opaque_owners.add(owner[insn.addr])
    successors = []
    predecessors = [set() for _ in fn]
    for i, insn in enumerate(fn):
        next_i = index.get(insn.addr + 4)
        mn = insn.mnemonic
        target = SPULifter._branch_target(insn)
        if mn in ("br", "bra"):
            edges = [index[target]] if target in index else []
        elif mn in _COND_BR:
            edges = [] if next_i is None else [next_i]
            if target in index:
                edges.append(index[target])
        elif mn in ("bi", "iret"):
            edges = []
        elif mn in ("stop", "stopd"):
            from find_spu_functions import is_resuming_stop
            edges = [next_i] if next_i is not None and is_resuming_stop(insn) else []
        else:
            edges = [] if next_i is None else [next_i]
        successors.append(edges)
        for successor in edges:
            predecessors[successor].add(i)

    # Roots start a new ABI link identity, never inherit another procedure's
    # slot. A known external landing in the middle has no ABI entry state.
    incoming = [None] * len(fn)
    pending = deque()
    queued = set()
    for i, insn in enumerate(fn):
        if insn.addr in starts and (insn.addr in independent or not predecessors[i]):
            incoming[i] = _LinkState(
                0, call_links.get(insn.addr, 1) == 1, frozenset())
        elif insn.addr in independent:
            incoming[i] = _LinkState(None, False, frozenset())
        if incoming[i] is not None:
            pending.append(i)
            queued.add(i)

    def matches_slot(state, insn):
        offset = _stack_link_load_offset(insn)
        return (offset is not None and state.sp_delta is not None
                and state.sp_delta + offset in state.slots
                and (state.inherited or insn.addr not in after_opaque))

    def transfer(state, insn):
        delta, link_value = state.sp_delta, state.live_link
        slots, private_slots = state.slots, state.private_slots
        live_private = state.live_link_private
        mn = insn.mnemonic
        ops = _ops(insn.operands)
        if mn == "ai" and len(ops) == 3 and _reg(ops[0]) == "1":
            immediate = _parse_imm_int(ops[2])
            delta = (delta + immediate if _reg(ops[1]) == "1"
                     and delta is not None and immediate is not None else None)
        elif (mn not in _NO_RT_WRITE and _dest_reg(insn) == 1
              and not _is_identity_move(insn)):
            delta = None
        if mn in ("stqd", "stqa", "stqr", "stqx"):
            if mn == "stqd":
                offset, reg = _disp_base(ops[1])
                offset = _parse_imm_int(offset) if offset is not None else None
                address_regs = () if reg is None else (int(reg),)
            elif mn == "stqx":
                offset, reg = None, None
                address_regs = ((insn.raw >> 7) & 0x7F, (insn.raw >> 14) & 0x7F)
            else:
                offset, reg, address_regs = None, None, ()
            stack_address = any(state.stack_derived & (1 << r) for r in address_regs)
            if mn == "stqd" and reg == "1" and delta is not None and offset is not None:
                address = delta + offset
                saved = set(slots)
                if _reg(ops[0]) == "0" and link_value:
                    saved.add(address)
                else:
                    saved.discard(address)
                slots = frozenset(saved)
                private_slots = private_slots - {address}
                if _reg(ops[0]) == "0" and link_value and live_private:
                    private_slots = private_slots | {address}
            elif stack_address:
                # A stack-derived address that cannot be placed may overwrite
                # any link slot. The private-slot assumption cannot excuse it.
                slots, private_slots = frozenset(), frozenset()
            else:
                # ABI assumption: argument/loaded/global pointers do not alias
                # a procedure's private link-save area.
                private_slots = slots
        if insn.addr in pc_getters:
            if (insn.raw & 0x7F) == 0:
                link_value, live_private = False, False
        elif mn in ("brsl", "brasl", "bisl", "bisled"):
            link_value, live_private = False, False
        elif _writes_r0(insn) and not _is_identity_move(insn):
            link_value = mn == "lqd" and matches_slot(state, insn)
            live_private = (link_value and state.sp_delta + _stack_link_load_offset(insn)
                            in state.private_slots)
        return _LinkState(delta, link_value, slots, state.inherited, state.callee_saved,
                          _stack_derived_after(insn, state.stack_derived), private_slots,
                          live_private)

    # First propagate rooted facts. Then give unrooted code an unknown state,
    # so a dead/cyclic predecessor never counts as an agreeing incoming edge.
    for seed_unknown in (False, True):
        if seed_unknown:
            for i in range(len(fn)):
                if incoming[i] is None:
                    incoming[i] = _LinkState(None, False, frozenset())
                    pending.append(i)
                    queued.add(i)
        while pending:
            i = pending.popleft()
            queued.discard(i)
            out = transfer(incoming[i], fn[i])
            for successor in successors[i]:
                address = fn[successor].addr
                if address in independent:
                    continue
                crossing = owner[fn[i].addr] != owner[address]
                abi_continuation = continuations.get(address) == fn[i].addr
                carried = _LinkState(
                    out.sp_delta, out.live_link, out.slots, out.inherited or crossing,
                    out.callee_saved or abi_continuation, out.stack_derived, out.private_slots,
                    out.live_link_private)
                old = incoming[successor]
                if old is None:
                    merged = carried
                else:
                    # A call may destroy the live link without changing the
                    # independently proven stack delta or saved-link contents.
                    slots = old.slots & carried.slots
                    merged = _LinkState(
                        old.sp_delta if old.sp_delta == carried.sp_delta else None,
                        old.live_link and carried.live_link, slots,
                        old.inherited or carried.inherited,
                        old.callee_saved or carried.callee_saved,
                        old.stack_derived | carried.stack_derived,
                        (old.private_slots | carried.private_slots) & slots,
                        old.live_link and carried.live_link
                        and (old.live_link_private or carried.live_link_private))
                if merged != old:
                    incoming[successor] = merged
                    if successor not in queued:
                        pending.append(successor)
                        queued.add(successor)

    loads, inherited_loads, callee_saved_loads, private_loads, refused = (
        set(), set(), set(), set(), {})
    for i, insn in enumerate(fn):
        if insn.mnemonic != "lqd" or not _writes_r0(insn):
            continue
        state = incoming[i]
        if state is not None and matches_slot(state, insn):
            loads.add(insn.addr)
            if state.inherited:
                inherited_loads.add(insn.addr)
            if state.callee_saved:
                callee_saved_loads.add(insn.addr)
            offset = _stack_link_load_offset(insn)
            if state.sp_delta + offset in state.private_slots:
                private_loads.add(insn.addr)
        elif _stack_link_load_offset(insn) is None:
            refused[insn.addr] = "non-stack-base"
        elif state is None:
            refused[insn.addr] = "no-proven-direct-entry"
        elif state.sp_delta is None:
            refused[insn.addr] = "unknown-or-conflicting-stack-delta"
        else:
            refused[insn.addr] = "no-dominating-matching-link-save"
    return loads, inherited_loads, callee_saved_loads, private_loads, refused


def _is_identity_move(insn) -> bool:
    """`ai $rX,$rX,0` / `ori $rX,$rX,0` -- writes rX but preserves its value.

    Sony's interrupt-window idiom needs a real instruction slot between the
    `bie` that enables interrupts and the `bid` that disables them again (that
    is the window a pending interrupt fires in), and uses `ai $r0,$r0,0` for it.
    A nearest-writer scan must look straight through it: it "writes" r0 without
    changing it, so the classification depends on whatever wrote r0 before.
    """
    if insn.mnemonic not in ("ai", "ori"):
        return False
    ops = _ops(insn.operands)
    return len(ops) == 3 and ops[0] == ops[1] and ops[2].strip() in ("0", "0x0")


def compute_bi_r0_jumps(insns, bounds, *, image=None, base=None, delta=0,
                        entry_points=()) -> BiR0Classification:
    """Classify register-targeted r0 branches not proven to return.

    An unchanged caller link, identity move, or a proven ABI stack-slot reload
    is a return. A memory load only qualifies when a dominating `stqd $r0,off(
    $r1)` saved the entry link and the classifier tracks `$r1` through `ai`
    adjustments to the matching `lqd`. Other writes dispatch the computed PC.

    An `ila`/`il` target also covers the interrupt-window idiom: `bid $r0`
    after `ila $r0,<resume>` resumes at that address, rather than returning.
    """
    jumps = set()
    link_restores = {}
    ordered = sorted(insns, key=lambda x: x.addr)
    idx_of = {ins.addr: i for i, ins in enumerate(ordered)}
    if not bounds or not ordered:
        return BiR0Classification()
    if base is None:
        base = ordered[0].addr
    if image is None:
        image = b"".join(insn.raw.to_bytes(4, "big") for insn in ordered)
    independent, resolved, continuations, call_links, pc_getters = _r0_link_entry_inventory(
        ordered, bounds, image, base, delta, entry_points)
    valid_restore_loads, inherited_loads, callee_saved_loads, private_loads, refused_loads = (
        _r0_link_restore_loads(
            ordered, bounds, independent, continuations, call_links, pc_getters))
    unproven = {}

    for (s, e) in bounds:
        fn = [i for i in ordered if s <= i.addr < e]
        for idx, insn in enumerate(fn):
            if _bi_target_reg(insn) != "0":
                continue
            # Stop at unconditional flow breaks: with coarse bounds, code above
            # such a break may belong to a different function's final block.
            decided = False
            only_identity = False
            for j in range(idx - 1, -1, -1):
                w = fn[j]
                if w.mnemonic in ("bi", "br", "bra", "iret", "stop", "stopd"):
                    break
                if w.addr in pc_getters and not _writes_r0(w):
                    continue
                if w.mnemonic in ("brsl", "brasl", "bisl", "bisled"):
                    jumps.add(insn.addr)
                    unproven[insn.addr] = "intervening-call"
                    decided = True
                    break
                if not _writes_r0(w):
                    continue
                if _is_identity_move(w):
                    only_identity = True
                    continue
                if w.mnemonic != "lqd" or w.addr not in valid_restore_loads:
                    jumps.add(insn.addr)
                    unproven[insn.addr] = refused_loads.get(
                        w.addr, f"computed-r0-write:{w.mnemonic}")
                else:
                    link_restores[insn.addr] = w.addr
                decided = True
                break
            if not decided and call_links.get(s, 1) != 1:
                jumps.add(insn.addr)
                unproven[insn.addr] = "entry-link-register-not-r0"
                continue
            if decided or not only_identity:
                continue
            # An identity-only block may be entered from the interrupt-enable
            # predecessor, where an earlier `ila $r0` supplies the resume PC.
            g = idx_of[insn.addr]
            for j in range(g - 1, max(-1, g - 1 - 12), -1):
                w = ordered[j]
                if not _writes_r0(w) or _is_identity_move(w):
                    continue
                if w.mnemonic in ("il", "ila"):
                    jumps.add(insn.addr)
                    unproven[insn.addr] = "predecessor-materialized-target"
                break
    link_restores = {site: load for site, load in link_restores.items() if site not in jumps}
    classification = BiR0Classification(jumps, link_restores)
    classification.pc_getters = pc_getters
    classification.unproven = unproven
    classification.inherited_returns = {
        site for site, load in link_restores.items() if load in inherited_loads
    }
    classification.callee_saved_returns = {
        site for site, load in link_restores.items() if load in callee_saved_loads
    }
    classification.private_slot_returns = {
        site for site, load in link_restores.items() if load in private_loads
    }
    link_returns = compute_link_returns(ordered, bounds)
    classification.link_returns = link_returns
    active = {address for start, end in bounds for address in range(start, end, 4)}
    for insn in ordered:
        if (insn.addr not in active or insn.addr in resolved or insn.addr in link_returns
                or insn.addr in pc_getters):
            continue
        target = _bi_target_reg(insn)
        if (insn.mnemonic in ("bisl", "bisled", "iret")
                or target is not None and (target != "0" or insn.addr in jumps)):
            classification.unresolved_branches.add(insn.addr)
    classification.return_assumptions = {
        site: classification.assumptions_for(site) for site in link_restores
    }
    return classification


def merge_chunk_groups(insns, bounds, max_insns, entry_points=()) -> dict:
    """Group contiguous chunks into function-sized runs for --merge-chunks.

    find_spu_functions starts a new "function" at every branch target, so a real
    function arrives as basic-block-sized chunks, and every branch between them
    is a trampoline: return to the drain loop, look up, call. A group runs from
    a chunk that starts a real function -- a brsl/brasl call target, an entry
    point, or the first chunk after a gap -- across every chunk contiguous with
    it, up to the next such start or the size cap. Returns {group_start: end}.
    Chunks inside a group are still lifted on their own as well (callers keep
    lifting every bound), so an indirect branch or a cross-function branch into
    the middle of a group still has a registered function to land on."""
    call_targets = set(entry_points)
    for ins in insns:
        if ins.mnemonic in ("brsl", "brasl"):
            tgt = SPULifter._branch_target(ins)
            if tgt is not None:
                call_targets.add(tgt)
    groups = {}
    ordered = sorted(bounds)
    i = 0
    while i < len(ordered):
        start, end = ordered[i]
        n = (end - start) // 4
        j = i + 1
        while (j < len(ordered) and ordered[j][0] == end
               and ordered[j][0] not in call_targets
               and n + (ordered[j][1] - ordered[j][0]) // 4 <= max_insns):
            end = ordered[j][1]
            n += (ordered[j][1] - ordered[j][0]) // 4
            j += 1
        if j > i + 1:
            groups[start] = end
        i = j
    return groups


def compute_link_returns(insns, bounds) -> set:
    """A `bi $rN` / conditional `bi{z,nz,hz,hnz} $rC,$rN` with N != 0 is emitted
    as a generic indirect branch, but Sony's SPU compiler also uses a NON-r0
    caller-saved register as the LINK register for leaf/helper calls: the caller
    does `brsl $rN, helper` (or `bisl $rN, ...`) and the helper returns via
    `bi $rN`. Modelled as a generic indirect branch, that return targets the
    caller's mid-function return address -- which is NOT a registered function
    entry -> branch-to-0 (observed: LBP's wwsjob policy module uses r4/r5/r6/r8/
    r78/r79 as link registers; e.g. `bi $r78` returned to 0x2C58/0x2D28/0x3048
    and stalled the whole WWS job engine).

    Detect it: rN is used as a link register somewhere in the image (the rt of
    some brsl/brasl/bisl/bisled), AND within the enclosing function block rN is a
    pure live-in -- never written before the branch. A COMPUTED branch (tail
    call, jump table, vtable dispatch) always materialises its target register
    in-block (lqx/rotqby/ai/il/ila...), so the write check excludes it; only a
    genuine link-register return leaves rN untouched. Then the branch is a
    RETURN -> emit a host `return;` so it composes with the brsl->C-call nesting,
    exactly like `bi $r0`. Returns the set of such branch addresses."""
    link_regs = set()
    for insn in insns:
        if insn.mnemonic in ("brsl", "brasl", "bisl", "bisled"):
            link_regs.add(insn.raw & 0x7F)
    link_regs.discard(0)   # r0 is handled by compute_bi_r0_jumps()
    if not link_regs:
        return set()

    returns = set()
    ordered = sorted(insns, key=lambda x: x.addr)

    # Predecessor map for the refinement below: every br/bra source per target.
    # A `bi $rN` whose block is ENTERED by a branch from a block that COMPUTED
    # rN (jump-table rotqby etc.) is a dispatch, not a return -- the write is
    # invisible to the in-bound liveness scan. Observed: pm_wwsjob's command
    # interpreter loads the handler into r6 from the LS 0x15B0 table (0x1BD8),
    # `br 0x2DF8` into the shared decode block, and dispatches via `bi $r6` at
    # 0x2E74; classifying that as a link-return silently skipped EVERY job
    # command handler (jobs never staged; LBP's loading queue never drained).
    preds: dict = {}
    for insn in ordered:
        if insn.mnemonic in ("br", "bra"):
            i16 = (insn.raw >> 7) & 0xFFFF
            if i16 & 0x8000:
                i16 -= 0x10000
            t = (i16 << 2) if insn.mnemonic == "bra" else (insn.addr + (i16 << 2))
            preds.setdefault(t & 0x3FFFF, []).append(insn.addr)
    idx_of_all = {ins.addr: i for i, ins in enumerate(ordered)}
    for (s, e) in bounds:
        fn = [i for i in ordered if s <= i.addr < e]
        for idx, insn in enumerate(fn):
            tr = _bi_target_reg(insn)
            if tr is None or tr == "0":
                continue
            try:
                rn = int(tr)
            except ValueError:
                continue
            if rn not in link_regs:
                continue
            # rN must be a pure live-in (the link address the caller planted):
            # if any earlier insn in this block writes rN (other than an identity
            # move), the target was computed here -> a real indirect branch, not
            # a return. Scan stops at unconditional flow breaks (block boundary
            # -- see the twin guard in compute_bi_r0_jumps).
            # Scan the real BASIC BLOCK, not the enclosing lifted function.
            # The two are not the same: the lifter splits long straight-line
            # runs into several functions that chain by fallthrough, and a scan
            # bounded by `fn` stops at a split that is not a control-flow edge
            # at all. pm_wwsjob's command-dispatch prologue is exactly that --
            # one 0x7C-byte block cut into five functions (0x2DF8, 0x2E18,
            # 0x2E38, 0x2E60, 0x2E78) -- so the `bi $r6` at 0x2E74 was examined
            # against the four instructions of 0x2E60..0x2E78 alone. Its
            # predecessor, the `br 0x2DF8` that loads r6 from the LS 0x15B0
            # handler table, enters the block far above that window and was
            # invisible, so the guard below could not fire and every job
            # command handler was skipped -- the very case its comment cites.
            written = False
            block_start = s
            gi = idx_of_all[insn.addr]
            for j in range(gi - 1, -1, -1):
                w = ordered[j]
                if w.mnemonic in ("bi", "br", "bra", "iret", "stop", "stopd"):
                    block_start = ordered[j + 1].addr
                    break
                if (w.mnemonic not in _NO_RT_WRITE and _dest_reg(w) == rn
                        and not _is_identity_move(w)):
                    written = True
                    break
            if written:
                continue
            # Predecessor refinement: rN is a live-in here -- but if a br/bra
            # ENTERS this block from a block whose tail COMPUTED rN, the value
            # is a dispatch target (jump table), not a caller's link.
            computed_in = False
            for t, srcs in preds.items():
                if not (block_start <= t <= insn.addr):
                    continue
                for src in srcs:
                    k = idx_of_all.get(src)
                    if k is None:
                        continue
                    for j in range(k - 1, max(-1, k - 24), -1):
                        w = ordered[j]
                        if w.mnemonic in ("bi", "br", "bra", "iret", "stop", "stopd"):
                            break
                        if (w.mnemonic not in _NO_RT_WRITE and _dest_reg(w) == rn
                                and not _is_identity_move(w)):
                            computed_in = True
                            break
                    if computed_in:
                        break
                if computed_in:
                    break
            if not computed_in:
                returns.add(insn.addr)
    return returns



# lv2 stop-and-signal syscalls that resume at the next instruction (the same
# set as find_spu_functions.LV2_RESUMING_STOPS, which decides function extents).
LV2_RESUMING_STOPS = {0x100, 0x110, 0x111}

class SPULifter:
    def __init__(self, trace: bool = False, prefix: str = "", overrides=None):
        self.functions: list[LiftedFunction] = []
        self.call_targets: set[int] = set()
        self.branch_targets: set[int] = set()
        self.unsupported: dict[str, int] = {}
        self.trace = trace
        self.overrides = dict(overrides or {})
        # Symbol prefix for all emitted spu_func_* / spu_recomp_register symbols.
        # Lets multiple lifted SPU images link into one binary without collisions
        # (every image otherwise exports spu_func_00000090 etc.). Empty = legacy.
        # A prefix that does not end in "_" still concatenates, but silently
        # yields symbols that violate the documented contract: "libsre" gives
        # libsrefunc_XXXX and libsrefunction_table, so an integration TU
        # declaring the documented libsre_function_table links against nothing.
        # YDKJ lost its real-libsre boot path to exactly that. Normalise, and
        # say so rather than fixing it up in silence.
        if prefix and not prefix.endswith("_"):
            sys.stderr.write(
                f"[spu_lifter] symbol prefix {prefix!r} has no trailing "
                f"underscore; using {prefix + chr(95)!r}"+chr(10))
            prefix += "_"
        self.prefix = prefix
        # --reloc: position-independent code a title copies to a different LS address
        # at each load (GoW:A's BatchJobList job code). It is lifted once at a canonical
        # base, and every local-store address the code materializes from its own pc
        # (links, lqr/stqr, transfer and return pcs) adds ctx->reloc_delta, which the
        # dispatcher sets to placement - canonical base on entry (spu_overlay_register_region_reloc).
        self.reloc = False
        # Computed transfers include every r0 write except an unchanged link or
        # a stack-slot reload proven by compute_bi_r0_jumps().
        self.bi_r0_jump: set = set()
        # Addresses of `bi/biz/... $rN` (N != 0) that are LINK-REGISTER RETURNS
        # (rN is a non-r0 link register the caller set via brsl/bisl) -- see
        # compute_link_returns(). Emitted as `return;` so they compose with the
        # brsl->C-call nesting instead of branching to an unregistered PC.
        self.link_return: set = set()

    def _function_symbol(self, addr: int) -> str:
        return self.overrides.get(addr, f"{self.prefix}spu_func_{addr:08X}")

    # ------------------------------------------------------------------ #
    def lift_function(self, insns: list[SPUInstruction],
                      start: int, end: int) -> LiftedFunction:
        func = LiftedFunction(name=f"{self.prefix}spu_func_{start:08X}",
                              start_addr=start, end_addr=end)

        internal: set[int] = set()
        for insn in insns:
            if insn.addr < start or insn.addr >= end:
                continue
            tgt = self._branch_target(insn)
            if tgt is not None and start <= tgt < end:
                internal.add(tgt)

        # Chunks merged into this function (--merge-chunks) are otherwise entered
        # through the drain loop, which delivers a pending SPU interrupt before
        # every transfer. As gotos they would not, and a job waiting in a loop
        # for its interrupt handler (DMA-list stall-and-notify) never wakes. So
        # each merged chunk entry hands back to the drain when one is pending.
        merged_starts = {a for a in getattr(self, "func_starts", ()) if start < a < end}
        last_insn = None
        for index, insn in enumerate(insns):
            if insn.addr < start or insn.addr >= end:
                continue
            if insn.addr in internal or insn.addr in merged_starts:
                func.body_lines.append(f"loc_{insn.addr:08X}:")
            if insn.addr in merged_starts:
                func.body_lines.append(
                    f"    if (ctx->int_enable && (ctx->event_status & ctx->event_mask)) "
                    f"{{ ctx->pc = {self._pc(insn.addr)}; g_spu_trampoline_fn = "
                    f"{self.prefix}spu_func_{insn.addr:08X}; return; }}")
            next_addr = None
            if insn.mnemonic == "bisl" and index + 1 < len(insns):
                candidate = insns[index + 1].addr
                if start <= candidate < end:
                    next_addr = candidate
            c = self._translate(insn, func, next_addr)
            if c:
                if self.trace:
                    func.body_lines.append(f"    spu_trace_pc(ctx, {self._pc(insn.addr)});")
                func.body_lines.append(f"    {c}")
                if self.trace and insn.mnemonic not in _NO_RT_WRITE:
                    rt_idx = insn.raw & 0x7F
                    func.body_lines.append(f"    spu_trace_rt(ctx, {rt_idx});")
            last_insn = insn

        # Fall-through chaining: if the final instruction does NOT unconditionally
        # end the basic block (i.e. it's a normal op, a call brsl/bisl, or a
        # conditional branch whose not-taken path continues), execution proceeds
        # into the next sequential function. Emit a tail-call so the chain isn't
        # truncated (this was silently dropping execution mid-job).
        _TERMINATORS = {"br", "bra", "bi", "iret", "stop", "stopd"}
        if (last_insn is not None
                and (last_insn.mnemonic not in _TERMINATORS
                     or (last_insn.mnemonic == "stop"
                         and (last_insn.raw & 0x3FFF) in LV2_RESUMING_STOPS))
                and end in getattr(self, "func_starts", set())):
            func.body_lines.append(
                f"    {{ SPU_DIRECT(ctx, {self._pc(end)}, {self._function_symbol(end)}); }}")

        # Infinite no-op self-loop (the SPU `br .` halt idiom): a function whose
        # whole body is nops + an unconditional branch back into itself does
        # nothing but spin. The default lifting renders it as `goto loc_<x>` --
        # an infinite C loop that hangs the SPU host thread forever (e.g. the
        # SPURS task runtime's terminal/idle state). Render it as a clean abort
        # (spu_halt longjmps back to the dispatcher) so the host thread returns.
        body_insns = [i for i in insns if start <= i.addr < end]
        if body_insns and all(i.mnemonic in ("nop", "lnop", "br", "bra")
                              for i in body_insns):
            last = body_insns[-1]
            ltgt = self._branch_target(last)
            if (last.mnemonic in ("br", "bra") and ltgt is not None
                    and start <= ltgt < end):
                func.body_lines = [
                    "    /* infinite no-op self-loop (SPU halt idiom) -> abort */",
                    "    spu_halt(ctx); return;",
                ]

        self.functions.append(func)
        return func

    def _pc(self, a: int) -> str:
        """A local-store address derived from the code's own placement: a constant, or
        under --reloc the canonical address plus ctx->reloc_delta (wrapped to LS)."""
        if self.reloc:
            return f"((0x{a:X}u + (uint32_t)ctx->reloc_delta) & 0x3FFFFu)"
        return f"0x{a:X}"

    @staticmethod
    def _branch_target(insn: SPUInstruction):
        """The literal target of a direct branch, or None if it has none.

        The target is always the LAST operand. `br`/`bra` carry only a target
        ("0x2D40"), but `brsl`/`brasl` carry the link register first
        ("$r0, 0x35A0") -- so reading operand 0 got the link register for every
        call, never matched "0x", and returned None. That made _translate emit
        `/* TODO spu: brsl unresolved target */` for EVERY brsl in EVERY image:
        the link register was set and the call silently dropped. 1,484 of them
        across LBP's 25 SPU images -- no SPU function call had ever run.

        It hid well because nothing downstream depends on this: the callee is
        still lifted (find_spu_functions scans all operands for targets, so the
        function exists and links), and a dropped call just falls through to the
        next instruction, which usually looks like plausible progress. LBP's
        wwsjob policy module spun forever at LS 0x2D68 because the one call in
        its loop -- `brsl $0,0x35a0`, which is what polls the workload and
        issues the DMA -- was one of these.
        """
        mn = insn.mnemonic
        ops = _ops(insn.operands)
        if mn not in ("br", "brsl", "bra", "brasl") and mn not in _COND_BR:
            return None
        tok = ops[-1] if ops else None
        if tok and tok.startswith("0x"):
            try:
                return int(tok, 16)
            except ValueError:
                return None
        return None

    # ------------------------------------------------------------------ #
    def _translate(self, insn: SPUInstruction, func: LiftedFunction,
                   next_addr=None) -> str:
        mn = insn.mnemonic
        ops = _ops(insn.operands)
        addr = insn.addr

        def rt(): return _reg(ops[0])
        def ra(): return _reg(ops[1])
        def rb(): return _reg(ops[2])
        def g(i): return f"ctx->gpr[{i}]"

        # ---- nop / sync / stop ----
        if mn in ("nop", "lnop"):
            return "/* nop */;"
        if mn in ("sync", "dsync", "syncc"):
            # SPU ISA v1.2 §13 + the 'Synchronize (Data)' pages: these order
            # earlier LS/channel accesses before later ones and publish LS for
            # external observers (Table 13-6 = our exact PPU-thread->SPU
            # handoff). Formerly a no-op -- the SPU twin of LESSONS #11d.
            # syncc's extra duty (channel-written execution state) is covered
            # structurally: our channel ops are locked host calls.
            return "spu_arch_fence();"
        if mn == "fscrwr":
            return "/* fscrwr: FP status/control write (no-op in recomp) */;"
        if mn == "stop":
            # Preserve the 14-bit stop-and-signal code: SPURS leaf tasks use
            # `stop <code>` to invoke kernel syscalls (EXIT/YIELD/WAIT_SIGNAL/...).
            code = insn.raw & 0x3FFF
            if code in LV2_RESUMING_STOPS:
                # lv2 services these and resumes at the next instruction (the
                # reply is read from the inbound mailbox right after the stop).
                # spu_stop puts the context back to RUNNING when it serviced it.
                return (f"ctx->stop_code = 0x{code:X}u; "
                        f"ctx->status = SPU_STATUS_STOPPED_BY_STOP; spu_stop(ctx); "
                        f"if (ctx->status != SPU_STATUS_RUNNING) return;")
            return (f"ctx->stop_code = 0x{code:X}u; "
                    f"ctx->status = SPU_STATUS_STOPPED_BY_STOP; spu_stop(ctx); return;")

        # ---- immediate loaders ----
        if mn == "il":
            return f"{g(rt())} = spu_il({_imm(ops[1])});"
        if mn == "ila":
            return f"{g(rt())} = spu_ila({_imm(ops[1])});"
        if mn == "ilh":
            return f"{g(rt())} = spu_ilh({_imm(ops[1])});"
        if mn == "ilhu":
            return f"{g(rt())} = spu_ilhu({_imm(ops[1])});"
        if mn == "iohl":
            return f"{g(rt())} = spu_iohl({g(rt())}, {_imm(ops[1])});"
        if mn == "fsmbi":
            return f"{g(rt())} = spu_fsmbi({_imm(ops[1])});"

        # addx / bgx: read rt as carry-in (and write rt)
        if mn == "addx":
            return f"{g(rt())} = spu_addx({g(ra())}, {g(rb())}, {g(rt())});"
        if mn == "bgx":
            return f"{g(rt())} = spu_bgx({g(ra())}, {g(rb())}, {g(rt())});"

        # Halt-on-condition: compiler/middleware assert traps (e.g. FMOD's
        # heqi rX,0 null-pointer guards). On real HW a taken halt stops the
        # SPU at the faulty data; emitting a no-op here let bad data sail
        # into silent million-iteration wedges. Honor the halt with a log.
        if mn in ("hgti", "hlgti", "heqi", "hgt", "hlgt", "heq"):
            pw = lambda i: f"{g(i)}._u32[0]"
            if mn == "heqi":
                cond = f"(int32_t){pw(ra())} == (int32_t)({_imm(ops[2])})"
            elif mn == "hgti":
                cond = f"(int32_t){pw(ra())} > (int32_t)({_imm(ops[2])})"
            elif mn == "hlgti":
                cond = f"{pw(ra())} > (uint32_t)({_imm(ops[2])})"
            elif mn == "heq":
                cond = f"{pw(ra())} == {pw(rb())}"
            elif mn == "hgt":
                cond = f"(int32_t){pw(ra())} > (int32_t){pw(rb())}"
            else:  # hlgt
                cond = f"{pw(ra())} > {pw(rb())}"
            return (f"if ({cond}) {{ extern void spu_halt(spu_context*); "
                    f"fprintf(stderr, \"[spu] HALT-ASSERT {mn} pc=0x{addr:05X} "
                    f"img=%d\\n\", ctx->image_id); "
                    f"ctx->status = SPU_STATUS_STOPPED_BY_HALT; "
                    f"spu_halt(ctx); return; }}")
        if mn == "stopd":
            # stopd has no code field; the architected stop code it reports is 0x3FFF (RPCS3 STOPD).
            return ("ctx->stop_code = 0x3FFFu; "
                    "ctx->status = SPU_STATUS_STOPPED_BY_STOP; spu_stop(ctx); return;")

        # dfceq, dfcmeq, dfcgt, dfcmgt, dftsv: the retail CBE SPU does not
        # implement them (later additions to the SPU ISA [INFERENCE]); on the
        # console executing one raises an SPU invalid-instruction error, the
        # thread group ends with join cause 4 after terminate and the stopped
        # thread's exit status reads 0x8001000F (CELL_ESTAT). Hardware, direct:
        # the hwprobe `spuexh` special-A probe ran each word alone in its own
        # thread group on a CECHC04 with 4.81 REBUG and none executed (issue
        # #124). The interpreter decodes them as `.word` and stops at the word;
        # lifted code must stop the same way, not call a helper and run on.
        # This deliberately does NOT take the `.word` fallthrough at the end of
        # this function: spu_unsupported tolerates data embedded in .text that
        # never executes, while these are ISA-defined opcodes the console
        # rejects, so any execution is a hard stop (fail closed), named with
        # the word, its pc and the image.
        if mn in ("dfceq", "dfcmeq", "dfcgt", "dfcmgt", "dftsv"):
            return (f"/* {mn}: invalid on the CBE SPU (hwprobe spuexh special A, issue #124) */ "
                    f"{{ extern void spu_halt(spu_context*); ctx->pc = 0x{addr:X}u; "
                    f"fprintf(stderr, \"[spu] INVALID-OP {mn} (0x%08X) at LS 0x%05X img=%d\\n\", "
                    f"0x{insn.raw:08X}u, 0x{addr:05X}u, ctx->image_id); "
                    f"ctx->status = SPU_STATUS_STOPPED_BY_HALT; spu_halt(ctx); return; }}")

        # cflts/cfltu at I8 <= 14: the conversion shifts by sh = be + 23 - I8, and a
        # lane with sh >= 264 (be >= 241 + I8, i.e. only at these scales) leaves the
        # hardware's saturating path for a result that is not modelled (cflts at every
        # such lane; cfltu except negative lanes and sh == 264, which were measured;
        # hwprobe spuexh lanes, CECHC04 with 4.81 REBUG, runs r014/r018/r019, issue
        # #126). Which lanes reach it depends on the data, so the lifted code computes
        # the conversion and, first, asks spu_cfl_unmodelled_lane() (the interpreter's
        # check, runtime/spu/spu_helpers.h): a lane that reaches the path stops the
        # run the same fail-closed way (named with the op, the scale, the lane, its
        # input word, the word, its pc and the image), not a value the console never
        # produced. I8 >= 15 cannot reach it (max sh = 263), so it lifts to the bare
        # helper call as before.
        if mn in ("cflts", "cfltu"):
            i8 = int(_imm(ops[2]), 0)
            if i8 <= 14:
                uns = 1 if mn == "cfltu" else 0
                src = g(ra())
                return (f"{{ int cfl_l = spu_cfl_unmodelled_lane({src}, {i8}, {uns}); "
                        f"if (cfl_l >= 0) {{ extern void spu_halt(spu_context*); ctx->pc = 0x{addr:X}u; "
                        f"fprintf(stderr, \"[spu] INVALID-OP {mn}: unmodelled cflts/cfltu lane ({mn} I8={i8} lane=%d in=0x%08X, #126) "
                        f"(0x%08X) at LS 0x%05X img=%d\\n\", "
                        f"cfl_l, (unsigned){src}._u32[cfl_l], 0x{insn.raw:08X}u, 0x{addr:05X}u, ctx->image_id); "
                        f"ctx->status = SPU_STATUS_STOPPED_BY_HALT; spu_halt(ctx); return; }} }} "
                        f"{g(rt())} = spu_{mn}({src}, {i8});")

        # ---- integer arithmetic (register) ----
        rr_bin = {
            "a": "spu_a", "sf": "spu_sf", "ah": "spu_ah", "sfh": "spu_sfh",
            "and": "spu_and", "or": "spu_or", "xor": "spu_xor",
            "nand": "spu_nand", "nor": "spu_nor", "andc": "spu_andc", "orc": "spu_orc",
            "ceq": "spu_ceq", "ceqh": "spu_ceqh", "ceqb": "spu_ceqb",
            "cgt": "spu_cgt", "cgth": "spu_cgth", "cgtb": "spu_cgtb",
            "clgt": "spu_clgt", "clgth": "spu_clgth", "clgtb": "spu_clgtb",
            "mpy": "spu_mpy", "mpyu": "spu_mpyu",
            "mpyh": "spu_mpyh", "mpyhh": "spu_mpyhh", "mpys": "spu_mpys",
            "fa": "spu_fa", "fs": "spu_fs", "fm": "spu_fm",
            "fi": "spu_fi",   # floating interpolate (reciprocal refine)
            "fceq": "spu_fceq", "fcgt": "spu_fcgt",
            "fcmeq": "spu_fcmeq", "fcmgt": "spu_fcmgt",
            # double-precision (2 doubles/reg); the double compares are above:
            # invalid on the CBE SPU, so they never reach a helper
            "dfa": "spu_dfa", "dfs": "spu_dfs", "dfm": "spu_dfm",
            "mpyhhu": "spu_mpyhhu",
            "eqv": "spu_eqv", "absdb": "spu_absdb", "avgb": "spu_avgb",
            "cg": "spu_cg", "bg": "spu_bg",
            "sumb": "spu_sumb",
            # double precision
            "dfa": "spu_dfa", "dfs": "spu_dfs", "dfm": "spu_dfm",
            # Phase 2: register-variable shifts/rotates
            "shl": "spu_shl", "shlh": "spu_shlh",
            "rot": "spu_rot", "roth": "spu_roth",
            "shlqbi": "spu_shlqbi",  "rotqbi": "spu_rotqbi",
            "shlqby": "spu_shlqby",  "rotqby": "spu_rotqby",
            "shlqbybi": "spu_shlqbybi", "rotqbybi": "spu_rotqbybi",
            # Phase 3: rotate-and-mask (register-variable)
            "rotm": "spu_rotm", "rotma": "spu_rotma",
            "rothm": "spu_rothm", "rotmah": "spu_rothma",
            "rotqmbi": "spu_rotqmbi", "rotqmby": "spu_rotqmby",
            "rotqmbybi": "spu_rotqmbybi",
            # Phase 3: indexed constant generators (insertion masks)
            "cbx": "spu_cbx", "chx": "spu_chx",
            "cwx": "spu_cwx", "cdx": "spu_cdx",
        }
        if mn in rr_bin:
            return f"{g(rt())} = {rr_bin[mn]}({g(ra())}, {g(rb())});"

        # ---- unary (register) ----
        rr_un = {
            "clz": "spu_clz", "cntb": "spu_cntb",
            "fscrrd": "spu_fscrrd",
            "gb": "spu_gb", "gbh": "spu_gbh", "gbb": "spu_gbb",
            "fesd": "spu_fesd", "frds": "spu_frds",
            "frsqest": "spu_frsqest", "frest": "spu_frest",
            "fesd": "spu_fesd", "frds": "spu_frds",   # single<->double convert
            # Phase 3
            "xsbh": "spu_xsbh", "xshw": "spu_xshw", "xswd": "spu_xswd",
            "orx": "spu_orx",
            "fsm": "spu_fsm", "fsmh": "spu_fsmh", "fsmb": "spu_fsmb",
            "mfspr": "spu_mfspr",
        }
        if mn in rr_un:
            return f"{g(rt())} = {rr_un[mn]}({g(ra())});"

        # ---- move register (or rt,ra,ra) handled by generic 'or' above ----

        # ---- arithmetic / logical / compare immediate ----
        ri_imm = {
            "ai": "spu_ai", "ahi": "spu_ahi", "sfi": "spu_sfi", "sfhi": "spu_sfhi",
            "andi": "spu_andi", "ori": "spu_ori", "xori": "spu_xori",
            "ceqi": "spu_ceqi", "cgti": "spu_cgti", "clgti": "spu_clgti",
            "ceqbi": "spu_ceqbi", "ceqhi": "spu_ceqhi",
            "clgtbi": "spu_clgtbi", "clgthi": "spu_clgthi",
            "cgthi": "spu_cgthi", "cgtbi": "spu_cgtbi",
            "mpyi": "spu_mpyi", "mpyui": "spu_mpyui",
            # Phase 3: halfword/byte immediate logic
            "andhi": "spu_andhi", "andbi": "spu_andbi",
            "orhi":  "spu_orhi",  "orbi":  "spu_orbi",
            "xorhi": "spu_xorhi", "xorbi": "spu_xorbi",
            # RI8 float<->int conversions with scale (i8 in ops[2])
            "cflts": "spu_cflts", "cfltu": "spu_cfltu",
            "csflt": "spu_csflt", "cuflt": "spu_cuflt",
        }
        if mn in ri_imm:
            return f"{g(rt())} = {ri_imm[mn]}({g(ra())}, {_imm(ops[2])});"

        # ---- shift / rotate immediate ----
        sh_imm = {
            "shli": "spu_shli", "shlhi": "spu_shlhi",
            "roti": "spu_roti", "rothi": "spu_rothi",
            "rotmi": "spu_rotmi", "rotmai": "spu_rotmai", "rotmhi": "spu_rotmhi",
            "rotmahi": "spu_rotmahi",
            "shlqbyi": "spu_shlqbyi", "rotqbyi": "spu_rotqbyi",
            "shlqbii": "spu_shlqbii", "rotqbii": "spu_rotqbii",
            # Phase 3: rotate-and-mask immediate + d-form constant generators
            "rothmi": "spu_rothmi",
            "rotqmbii": "spu_rotqmbii", "rotqmbyi": "spu_rotqmbyi",
            "cbd": "spu_cbd", "chd": "spu_chd",
            "cwd": "spu_cwd", "cdd": "spu_cdd",
        }
        if mn in sh_imm:
            # Disassembler quirk: the quad shift/rotate RI7 forms (shlqbyi,
            # rotqbyi, shlqbii, rotqbii) are matched against SPU_RR first and
            # therefore emitted with 3-register operands, with the i7 bits
            # disguised as "$rN". The register index IS the immediate value,
            # so we strip the "$r" and use the digits literally.
            tok = ops[2]
            if tok.startswith("$r"):
                tok = tok[2:]
            else:
                tok = _imm(tok)
            return f"{g(rt())} = {sh_imm[mn]}({g(ra())}, {tok});"

        # ---- select / shuffle (RRR: rt, ra, rb, rc) ----
        if mn == "selb":
            rc = _reg(ops[3])
            return f"{g(rt())} = spu_selb({g(ra())}, {g(rb())}, {g(rc)});"
        if mn == "shufb":
            rc = _reg(ops[3])
            return f"{g(rt())} = spu_shufb({g(ra())}, {g(rb())}, {g(rc)});"
        if mn in ("fma", "fms", "fnms", "mpya"):
            rc = _reg(ops[3])
            return f"{g(rt())} = spu_{mn}({g(ra())}, {g(rb())}, {g(rc)});"
        # sfx: extended subtract — RT is also a source (carry-in = low bit of old RT).
        if mn == "sfx":
            return f"{g(rt())} = spu_sfx({g(ra())}, {g(rb())}, {g(rt())});"
        # cgx: extended carry-generate — RT is also a source (carry-in = low bit).
        if mn == "cgx":
            return f"{g(rt())} = spu_cgx({g(ra())}, {g(rb())}, {g(rt())});"
        # double FMA (dfma/dfms/dfnms/dfnma): 3-register, RT is the accumulator (c).
        if mn in ("dfma", "dfms", "dfnms", "dfnma"):
            return f"{g(rt())} = spu_{mn}({g(ra())}, {g(rb())}, {g(rt())});"
        # mpyhha/mpyhhau: high-half multiply accumulated into RT (3-register).
        if mn in ("mpyhha", "mpyhhau"):
            return f"{g(rt())} = spu_{mn}({g(ra())}, {g(rb())}, {g(rt())});"

        # ---- quadword loads / stores ----
        if mn == "lqd":
            disp, base = _disp_base(ops[1])
            if disp is not None:
                return f"{g(rt())} = spu_ls_read128(ctx, {g(base)}._u32[0] + {disp});"
        if mn == "stqd":
            disp, base = _disp_base(ops[1])
            if disp is not None:
                return f"spu_ls_write128(ctx, {g(base)}._u32[0] + {disp}, {g(rt())});"
        if mn in ("lqa", "lqr"):
            # lqr's address is pc-relative (the disassembler gives it absolute): under --reloc it moves with the code
            a = self._pc(int(_imm(ops[1]), 0)) if mn == "lqr" and self.reloc else _imm(ops[1])
            return f"{g(rt())} = spu_ls_read128(ctx, {a});"
        if mn in ("stqa", "stqr"):
            a = self._pc(int(_imm(ops[1]), 0)) if mn == "stqr" and self.reloc else _imm(ops[1])
            return f"spu_ls_write128(ctx, {a}, {g(rt())});"
        if mn == "lqx":
            return f"{g(rt())} = spu_ls_read128(ctx, {g(ra())}._u32[0] + {g(rb())}._u32[0]);"
        if mn == "stqx":
            return f"spu_ls_write128(ctx, {g(ra())}._u32[0] + {g(rb())}._u32[0], {g(rt())});"

        # ---- channel ops ----
        if mn == "rdch":
            return f"{g(rt())} = spu_rdch(ctx, {_chan(ops[1])});"
        if mn == "rchcnt":
            # CBEA: the count lands in the PREFERRED word, remaining slots ZERO
            # (splatting it is the spu_link bug class; RPCS3 = v128::from32r).
            return f"{g(rt())} = spu_pref_u32(spu_rchcnt(ctx, {_chan(ops[1])}));"
        if mn == "wrch":
            # operands: channel, $rt
            return f"spu_wrch(ctx, {_chan(ops[0])}, {g(_reg(ops[1]))});"

        # ---- branches ----
        if mn in ("br", "bra"):
            tgt = self._branch_target(insn)
            # SELF-LOOP TRAP: `br .` (target == this instruction) is an infinite
            # hang on real SPU -- a deliberate trap, no forward progress. Emitting
            # `goto loc_self` busy-spins the host thread forever; stop the SPU
            # instead (same halt path the lifter emits for a `stop` instruction).
            if tgt == addr:
                return "ctx->status = SPU_STATUS_STOPPED_BY_HALT; return;"
            return self._uncond_branch(tgt, func, addr)
        if mn in ("brsl", "brasl"):
            # The disassembler drops the link register from brsl operands, so
            # recover it from the raw encoding (rt = bits 25-31 = raw & 0x7F).
            link_rt = insn.raw & 0x7F
            tgt = self._branch_target(insn)
            # Link register: preferred word only, other slots ZERO (real HW /
            # RPCS3 v128::from32r) -- splatting corrupts full-quadword link use.
            link = f"{g(link_rt)} = spu_link({self._pc((addr + 4) & 0x3FFFC)});"   # wraps at the end of LS
            # SELF-LOOP TRAP: `brsl rX, .` (target == this instruction) is an
            # infinite loop on real SPU (re-sets the link each pass, never
            # advances) -- a trap, NOT a call. Emitting a host call recurses
            # forever -> host stack overflow -> segfault (observed crashing the
            # boot in cri_audio_00023C58). Set the link, then stop the SPU (same
            # halt path the lifter emits for a `stop` instruction).
            if tgt == addr:
                return f"{link} ctx->status = SPU_STATUS_STOPPED_BY_HALT; return;"
            # PC-GETTER IDIOM: `brsl rX, .+4` (target == next instruction) just
            # loads PC+4 into rX for PC-relative addressing / computed jump tables;
            # it is NOT a real call. Emitting a host call here imbalances the C
            # call/return nesting -- the "callee" falls through into the rest of
            # the function and a later `bi $r0` return unwinds to this brsl's frame
            # instead of the real caller (observed: SPURS taskset LoadElf's return
            # landed back inside its own clear loop, running it with a stale count).
            # Treat it as: set the link, then fall through to addr+4.
            if tgt == addr + 4:
                return f"{link} {self._uncond_branch(addr + 4, func, addr)}"
            if tgt is not None:
                self.call_targets.add(tgt)
                # Nested host call bracketed by host_depth (so the callee's
                # `bi $r0` returns via host return) + SPU_DRAIN (drains the
                # callee's own tail-chains so they don't grow the caller frame)
                # + image save/restore (adopt-on-serve cannot leak upward).
                # --reloc: the callee's drain may dispatch into other placed code, which sets
                # ctx->reloc_delta for itself; put this placement's back on return.
                rs, rr = ("const int32_t _rd = ctx->reloc_delta; ", " ctx->reloc_delta = _rd;") if self.reloc else ("", "")
                return (f"{link} {{ int32_t _si = (int32_t)ctx->image_id; {rs}"
                        f"ctx->host_depth++; {self._function_symbol(tgt)}(ctx); "
                        f"spu_drain_call(ctx, {self._pc(addr + 4)}); ctx->host_depth--; spu_img_restore(ctx, _si);{rr} }}")
            return f"{link} /* TODO spu: brsl unresolved target */;"
        if mn in _COND_BR:
            tgt = self._branch_target(insn)
            cond = self._cond(mn, _reg(ops[0]))
            if tgt is None:
                return (f'/* TODO spu: {mn} {insn.operands} */ '
                        f'spu_unsupported(0x{insn.addr:X}, "{mn}");')
            if func.start_addr <= tgt < func.end_addr:
                # A loop has a backward edge; only that one counts against the
                # budgeted twin's budget (SPU_LIFT_BACKEDGE, spu_context.h), and
                # it expands to nothing in the production compilation.
                if tgt <= addr:
                    return f"if ({cond}) {{ SPU_LIFT_BACKEDGE(ctx); goto loc_{tgt:08X}; }}"
                return f"if ({cond}) goto loc_{tgt:08X};"
            self.branch_targets.add(tgt)
            # Cross-function conditional branch = conditional tail: a direct
            # tail call when the drain has nothing to do on this step, else
            # the trampoline and unwind (SPU_DIRECT, spu_context.h).
            return (f"if ({cond}) {{ SPU_DIRECT(ctx, {self._pc(tgt)}, "
                    f"{self._function_symbol(tgt)}); }}")
        # Interrupt enable/disable bits on the bi family (bie/bid, irete/iretd,
        # bisle(d)...): bit 0x40000 = E (enable), 0x80000 = D (disable), taking
        # effect when the branch is TAKEN. The WWS jobmanager's poll loop runs
        # under bie/bid interrupt windows; dropping the bits starves its DMA
        # stall-and-notify handler and wedges the whole job pipeline.
        _ied = ("ctx->int_enable = 1; " if insn.raw & 0x40000 else
                "ctx->int_enable = 0; " if insn.raw & 0x80000 else "")
        # For bi/bisl the disassembler emits only "$rA" (ops[0] = target reg).
        if mn in ("bi",):
            tgt_reg = _reg(ops[0])
            # SPU ABI: $r0 is the link register. `bi $r0` is the standard
            # function return — translate to a host return so call/return
            # discipline matches the C function nesting from brsl. EXCEPTION:
            # when r0 was reloaded from memory (lqa/lqr) it is a COMPUTED TAIL
            # JUMP (e.g. the SPURS task launch `lqa $r0,savedContextLr; bi $r0`),
            # flagged by compute_bi_r0_jumps() — emit the indirect dispatch.
            if (tgt_reg == "0" and addr not in self.bi_r0_jump) \
                    or addr in self.link_return:
                # SPU_RET: host return while a matched brsl frame is live
                # (host_depth>0); at 0 the frame was destroyed -> dispatch to r0.
                # A return through a NON-r0 link (compute_link_returns) must
                # publish THAT register as the return PC: SPU_RET publishes r0,
                # and spu_drain_call restarts dispatch when pc != return_pc.
                if tgt_reg != "0":
                    return f"{_ied}SPU_RET_REG(ctx, {tgt_reg});"
                return f"{_ied}SPU_RET(ctx);"
            # Computed indirect tail: set pc + trampoline to the dispatcher, unwind.
            return (f"SPU_LIFT_BACKEDGE(ctx); {_ied}ctx->pc = {g(tgt_reg)}._u32[0]; "
                    f"g_spu_trampoline_fn = spu_indirect_branch; return;")
        # iret: interrupt return -> branch to the saved interrupt PC (SRR0).
        if mn == "iret":
            return (f"SPU_LIFT_BACKEDGE(ctx); {_ied}ctx->pc = ctx->srr0; "
                    "g_spu_trampoline_fn = spu_indirect_branch; return;")
        if mn in ("bisl",):
            # `bisl rt, ra`: rt = link, ra = TARGET. The disassembler emits BOTH
            # ("$r0, $r2"), so operand 0 is the link register -- taking it as the
            # target made every indirect call branch to its own return address
            # instead of the callee. LBP's wwsjob policy module halted at exactly
            # that: `bisl $0,$2` at LS 0x3598 calls selectWorkload through the
            # kernel context, and we jumped to 0x359C (its own link) instead.
            link_rt = insn.raw & 0x7F            # rt = bits 25-31 of the encoding
            # Equality may use C fall-through only when that exact next
            # instruction is represented here; range ends and LS wrap must
            # still dispatch even when the target equals the link value.
            tgt_reg = _reg(ops[-1])
            # Indirect call: nested dispatch bracketed like brsl (host_depth +
            # SPU_DRAIN + image save/restore) so the callee's tail-chains drain
            # here and its `bi $r0` returns via host return.
            # read the target BEFORE writing the link: rt may be the same register as ra
            rs, rr = ("const int32_t _rd = ctx->reloc_delta; ", " ctx->reloc_delta = _rd;") if self.reloc else ("", "")
            falls_through = next_addr == addr + 4 and addr + 4 < 0x40000
            guard = "if (_tg != _ret) { " if falls_through else ""
            guard_end = " }" if falls_through else ""
            return (f"{{ uint32_t _tg = {g(tgt_reg)}._u32[0] & 0x3FFFCu; "
                    f"const uint32_t _ret = {self._pc((addr + 4) & 0x3FFFC)}; "
                    f"{g(link_rt)} = spu_link(_ret); {_ied}ctx->pc = _tg; "
                    f"{guard}int32_t _si = (int32_t)ctx->image_id; {rs}"
                    f"ctx->host_depth++; "
                    f"spu_indirect_branch(ctx); spu_drain_call(ctx, _ret); "
                    f"ctx->host_depth--; spu_img_restore(ctx, _si);{rr}{guard_end} }}")
        # bisled: set link, branch to RA only if an external event is pending.
        if mn in ("bisled",):
            link_rt = insn.raw & 0x7F            # rt = link
            tgt_reg = (insn.raw >> 7) & 0x7F     # ra = target (the disassembler's last operand is rb, not the target)
            # read the target before writing the link: rt may alias ra
            return (f"{{ uint32_t _tg = {g(tgt_reg)}._u32[0]; {g(link_rt)} = spu_link({self._pc((addr + 4) & 0x3FFFC)}); "
                    f"if ((ctx->event_status & ctx->event_mask) != 0) {{ "
                    f"{_ied}ctx->pc = _tg; SPU_LIFT_BACKEDGE(ctx); "
                    f"g_spu_trampoline_fn = spu_indirect_branch; return; }} }}")
        # biz/binz/bihz/bihnz: ops[0] = condition reg, ops[1] = target reg.
        if mn in ("biz", "binz", "bihz", "bihnz"):
            cond = self._cond(mn[1:], _reg(ops[0]))   # strip leading 'b' -> iz/inz...
            tgt_reg = _reg(ops[1])
            # $r0 is the link register: a conditional branch to it is a
            # conditional function return — emit a host return so it composes
            # with the brsl->C-call nesting (mirrors the `bi $r0` case above).
            # Dispatching to the return address would miss the C frame and
            # land on an unregistered mid-function PC.
            if (tgt_reg == "0" and addr not in self.bi_r0_jump) \
                    or addr in self.link_return:
                if tgt_reg != "0":
                    return f"if ({cond}) {{ {_ied}SPU_RET_REG(ctx, {tgt_reg}); }}"
                return f"if ({cond}) {{ {_ied}SPU_RET(ctx); }}"
            return (f"if ({cond}) {{ SPU_LIFT_BACKEDGE(ctx); {_ied}ctx->pc = {g(tgt_reg)}._u32[0]; "
                    f"g_spu_trampoline_fn = spu_indirect_branch; return; }}")

        # hint-for-branch: pure performance hint, safe to drop
        if mn in ("hbr", "hbra", "hbrr"):
            return "/* branch hint (ignored) */;"
        # mtspr: SPU special-purpose-register writes are ignored (RPCS3: SPRs unused)
        if mn == "mtspr":
            return "/* mtspr: SPR write ignored */;"

        # ---- fallthrough: unsupported ----
        self.unsupported[mn] = self.unsupported.get(mn, 0) + 1
        return (f'/* TODO spu: {mn} {insn.operands} */ '
                f'spu_unsupported(0x{insn.addr:X}, "{mn}");')

    # ------------------------------------------------------------------ #
    def _cond(self, mn: str, reg: str) -> str:
        """Condition expression on preferred slot for conditional branches."""
        word = f"ctx->gpr[{reg}]._u32[0]"
        half = f"ctx->gpr[{reg}]._u16[0]"   # preferred halfword = BE bytes 2-3 = LOW half of native _u32[0]
        table = {
            "brz": f"{word} == 0",      "brnz": f"{word} != 0",
            "brhz": f"{half} == 0",     "brhnz": f"{half} != 0",
            "iz": f"{word} == 0",       "inz": f"{word} != 0",
            "ihz": f"{half} == 0",      "ihnz": f"{half} != 0",
        }
        return table.get(mn, f"{word} != 0")

    def _uncond_branch(self, tgt, func: LiftedFunction, src: int) -> str:
        """`src` is the branch's own address: a goto to it or below closes a loop."""
        if tgt is None:
            return "/* TODO spu: unresolved branch */;"
        if func.start_addr <= tgt < func.end_addr:
            if tgt <= src:
                return f"{{ SPU_LIFT_BACKEDGE(ctx); goto loc_{tgt:08X}; }}"
            return f"goto loc_{tgt:08X};"
        self.branch_targets.add(tgt)
        # Cross-function unconditional tail: a direct tail call when the
        # drain has nothing to do on this step, else hand the target to the
        # trampoline and unwind so the enclosing SPU_DRAIN re-enters (no
        # host-stack growth either way; SPU_DIRECT, spu_context.h).
        return (f"{{ SPU_DIRECT(ctx, {self._pc(tgt)}, {self._function_symbol(tgt)}); }}")

    # ------------------------------------------------------------------ #
    def twin_renames(self) -> list[str]:
        """The symbols this image defines or references, for the twin's rename block."""
        defined = {f.start_addr for f in self.functions}
        names = [f.name for f in self.functions]
        names += [f"{self.prefix}spu_func_{t:08X}"
                  for t in sorted(self.call_targets | self.branch_targets) if t not in defined]
        names.append(f"{self.prefix}spu_recomp_register")
        return names

    def emit_header(self) -> str:
        lines = [HEADER_PREAMBLE, ""]
        # The budgeted twin is this very source compiled a second time with
        # SPU_LIFT_BUDGET (docs/SPU_XDIFF.md section 10). Both objects go into one
        # program, so the twin's symbols are renamed here, once, and the text of
        # the functions stays what it is. Without the definition this block is
        # skipped and the production object is unchanged.
        lines.append("#ifdef SPU_LIFT_BUDGET")
        for n in self.twin_renames():
            lines.append(f"#define {n} {n}{TWIN_SUFFIX}")
        lines.append("#endif")
        lines.append("")
        for f in self.functions:
            lines.append(f"void {f.name}(spu_context* ctx);")
        for symbol in sorted(set(self.overrides.values())):
            lines.append(f"void {symbol}(spu_context* ctx); /* native override */")
        defined = {f.start_addr for f in self.functions}
        for t in sorted(self.call_targets | self.branch_targets):
            if t not in defined:
                lines.append(f"void {self.prefix}spu_func_{t:08X}(spu_context* ctx); /* external */")
        lines.append("")
        lines.append("/* Runtime glue (runtime/spu/spu_channels.c) */")
        lines.append("void spu_register_function(uint32_t addr, void (*fn)(spu_context*));")
        if self.overrides:
            lines.append("void spu_register_function_with_reference(uint32_t addr, "
                         "void (*fn)(spu_context*), void (*reference)(spu_context*), int native_override);")
        lines.append("/* Call once at init to register this image's functions for")
        lines.append(" * indirect-branch dispatch (spu_indirect_branch). */")
        lines.append(f"void {self.prefix}spu_recomp_register(void);")
        lines.append("")
        return "\n".join(lines)

    def emit_source(self,header_name: str) -> str:
        lines = [SOURCE_PREAMBLE.format(header_name=header_name), ""]
        weak = "__attribute__((weak)) " if getattr(self, "weak_emit", False) else ""
        for f in self.functions:
            lines.append(f"void {weak}{f.name}(spu_context* ctx) {{")
            for b in f.body_lines:
                lines.append(b if b.endswith(":") else f"    {b}")
            lines.append("}")
            lines.append("")

        # Stubs for cross-function branch/call targets the function-boundary
        # detector did not promote to standalone functions. The lifter emits
        # `spu_func_<tgt>(ctx)` calls eagerly, so the linker needs a symbol;
        # at runtime we route through spu_indirect_branch which either lands
        # on a registered mid-function entry (if one was emitted) or halts
        # cleanly with a "PC X not registered" diagnostic.
        defined = {f.start_addr for f in self.functions}
        externs = sorted((self.call_targets | self.branch_targets) - defined)
        if externs:
            lines.append("/* Indirect-dispatch stubs for cross-function targets the")
            lines.append(" * function detector did not seed (typically conditional")
            lines.append(" * branches that escape a function's range). */")
            for t in externs:
                lines.append(f"void {self.prefix}spu_func_{t:08X}(spu_context* ctx) {{")
                pc = self._pc(t) if self.reloc else f"0x{t:X}u"
                lines.append(f"    ctx->pc = {pc}; "
                             f"g_spu_trampoline_fn = spu_indirect_branch; return;")
                lines.append("}")
            lines.append("")

        lines.append("/* Function table */")
        lines.append("typedef struct { uint32_t addr; void (*func)(spu_context*); "
                     "void (*reference)(spu_context*); int native_override; const char* name; } spu_func_entry;")
        lines.append("static const spu_func_entry spu_function_table[] = {")
        for f in self.functions:
            selected = self._function_symbol(f.start_addr)
            is_override = 1 if f.start_addr in self.overrides else 0
            lines.append(f'    {{ 0x{f.start_addr:08X}u, {selected}, {f.name}, {is_override}, "{f.name}" }},')
        lines.append("    { 0, NULL, NULL, 0, NULL }")
        lines.append("};")
        lines.append("")
        lines.append(f"void {self.prefix}spu_recomp_register(void) {{")
        lines.append("    ps3_spu_lifter_abi_check(SPU_LIFTER_ABI);")
        if self.overrides:
            lines.append("    for (const spu_func_entry* e = spu_function_table; e->func; ++e) {")
            lines.append("        if (e->native_override)")
            lines.append("            spu_register_function_with_reference(e->addr, e->func, e->reference, 1);")
            lines.append("        else")
            lines.append("            spu_register_function(e->addr, e->func);")
            lines.append("    }")
        else:
            lines.append("    for (const spu_func_entry* e = spu_function_table; e->func; ++e)")
            lines.append("        spu_register_function(e->addr, e->func);")
        lines.append("}")
        lines.append("")
        return "\n".join(lines)

