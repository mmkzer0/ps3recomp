"""Generate or check the runtime diagnostics index (docs/DIAGNOSTICS.md).

The index is generated from the environment variables the runtime reads, but the
file itself is hand-maintained prose, so regeneration would rewrite ~1,400 lines
of reviewed text. `--check` enforces the part that must not drift: every knob the
sources read is listed in the document, and the document lists nothing else.
"""
import argparse
import collections
import os
import re
import sys

NL = chr(10)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOTS = [os.path.join(ROOT, r) for r in ('runtime', 'libs', 'tools')]
DOC = os.path.join(ROOT, 'docs', 'DIAGNOSTICS.md')
PAT = re.compile(r'getenv\(\s*"([A-Za-z_][A-Za-z_0-9]*)"\s*\)')
COMMENT = re.compile(r'^\s*(?:/\*|\*|//)\s?(.*)$')
# A knob entry as the generator writes it: - **`NAME`** — description
KNOB = re.compile(r'^- \*\*`([A-Za-z_][A-Za-z_0-9]*)`\*\*', re.M)
# The headline count and the per-group summary table.
HEADER = re.compile(r'\*\*(\d+) knobs across (\d+) groups\.\*\*')
GROUP_ROW = re.compile(r'^\| `([A-Za-z0-9]+)_\*` \| (\d+) \|$', re.M)


def strip_comments(text, python):
    """Blank out comments but keep every newline, so line numbers stay true.

    A getenv() inside commented-out code is not a knob; without this the
    index grew an entry for the example in boot_main.cpp's comment.
    """
    text = re.sub(r'/\*.*?\*/', lambda m: NL * m.group(0).count(NL), text, flags=re.S)
    text = re.sub(r'//[^\n]*', '', text)
    if python:
        text = re.sub(r'#[^\n]*', '', text)
    return text


def scan():
    """Every environment knob the sources read: name -> [(file, line, desc)]."""
    hits = collections.defaultdict(list)
    for root in ROOTS:
        for dp, _dn, fn in os.walk(root):
            if '.git' in dp:
                continue
            for f in fn:
                if not f.endswith(('.c', '.cpp', '.h', '.hpp', '.m', '.py')):
                    continue
                p = os.path.join(dp, f)
                try:
                    text = open(p, encoding='utf-8', errors='replace').read()
                except Exception:
                    continue
                lines = text.split(NL)
                code = strip_comments(text, f.endswith('.py')).split(NL)
                for i, l in enumerate(code):
                    for m in PAT.finditer(l):
                        name = m.group(1)
                        # nearest preceding comment block, up to 6 lines back
                        desc = ''
                        for j in range(i - 1, max(-1, i - 7), -1):
                            c = COMMENT.match(lines[j])
                            if c:
                                t = c.group(1).strip()
                                if t and not t.startswith('---'):
                                    desc = t if not desc else t + ' ' + desc
                            elif desc:
                                break
                            elif lines[j].strip():
                                break
                        # a same-line trailing comment wins
                        tc = re.search(r'/\*\s*(.*?)\s*\*/|//\s*(.*)$', lines[i])
                        if tc and (tc.group(1) or tc.group(2)):
                            desc = (tc.group(1) or tc.group(2)).strip()
                        rel = os.path.relpath(p, ROOT).replace(os.sep, '/')
                        hits[name].append((rel, i + 1, desc))
    return hits


def generate(hits):
    groups = collections.defaultdict(list)
    for name, locs in hits.items():
        groups[name.split('_')[0]].append((name, locs))

    out = []
    out.append('# Runtime diagnostics')
    out.append('')
    out.append('> Generated by `tools/gen_diagnostics_index.py`. Do not edit by hand.')
    out.append('')
    out.append('Every environment variable the runtime reads, with where it is read and')
    out.append('whatever the source says about it. **%d knobs across %d groups.**'
               % (len(hits), len(groups)))
    out.append('')
    out.append('Most are read once, at first use, and cached — so they are set before launch,')
    out.append('not changed while a title runs.')
    out.append('')
    out.append('| group | knobs |')
    out.append('|---|---|')
    for pre in sorted(groups, key=lambda k: -len(groups[k])):
        out.append('| `%s_*` | %d |' % (pre, len(groups[pre])))
    out.append('')
    for pre in sorted(groups):
        out.append('## `%s`' % pre)
        out.append('')
        for name, locs in sorted(groups[pre]):
            f, ln, desc = locs[0]
            extra = '' if len(locs) == 1 else '  _(+%d more sites)_' % (len(locs) - 1)
            out.append('- **`%s`** — %s' % (name, desc if desc else '_(no description in source)_'))
            out.append('  `%s:%d`%s' % (f, ln, extra))
        out.append('')
    return NL.join(out) + NL


def check(hits, doc):
    """Fail when the document and the sources disagree about the knob set."""
    try:
        text = open(doc, encoding='utf-8', errors='replace').read()
    except FileNotFoundError:
        print('FAIL: %s does not exist' % os.path.relpath(doc, ROOT), file=sys.stderr)
        return 1
    listed = KNOB.findall(text)
    source = set(hits)
    docset = set(listed)
    missing = sorted(source - docset)   # read by the sources, absent from the doc
    extra = sorted(docset - source)     # listed in the doc, no longer read
    dupes = sorted({n for n in listed if listed.count(n) > 1})
    groups = collections.Counter(name.split('_')[0] for name in source)
    bad_counts = []
    m = HEADER.search(text)
    if not m:
        bad_counts.append('missing the "**N knobs across M groups.**" headline')
    elif (int(m.group(1)), int(m.group(2))) != (len(source), len(groups)):
        bad_counts.append('headline says %s knobs across %s groups, the sources read %d across %d'
                          % (m.group(1), m.group(2), len(source), len(groups)))
    rows = dict((name, int(n)) for name, n in GROUP_ROW.findall(text))
    for name in sorted(set(groups) | set(rows)):
        if name not in rows:
            bad_counts.append('no summary-table row for `%s_*`' % name)
        elif name not in groups:
            bad_counts.append('summary-table row `%s_*` names no group in the sources' % name)
        elif rows[name] != groups[name]:
            bad_counts.append('summary-table row `%s_*` says %d, the sources read %d'
                              % (name, rows[name], groups[name]))
    if missing or extra or dupes or bad_counts:
        for name in missing:
            print('FAIL: `%s` is read by the sources but missing from %s'
                  % (name, os.path.relpath(doc, ROOT)), file=sys.stderr)
        for name in extra:
            print('FAIL: `%s` is listed in %s but no source reads it'
                  % (name, os.path.relpath(doc, ROOT)), file=sys.stderr)
        for name in dupes:
            print('FAIL: `%s` is listed more than once in %s'
                  % (name, os.path.relpath(doc, ROOT)), file=sys.stderr)
        for msg in bad_counts:
            print('FAIL: %s' % msg, file=sys.stderr)
        print('%d missing, %d stale, %d duplicated, %d count mismatch(es)'
              % (len(missing), len(extra), len(dupes), len(bad_counts)), file=sys.stderr)
        return 1
    print('OK: %s lists all %d knobs the sources read'
          % (os.path.relpath(doc, ROOT), len(source)))
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true',
                    help='compare the hand-maintained doc with the sources; exit 1 on drift')
    ap.add_argument('--doc', default=DOC,
                    help='document to check (default: docs/DIAGNOSTICS.md)')
    args = ap.parse_args()

    hits = scan()
    if args.check:
        return check(hits, args.doc)

    with open(args.doc, 'w', encoding='utf-8') as f:
        f.write(generate(hits))
    print('wrote %s: %d knobs, %d groups'
          % (os.path.relpath(args.doc, ROOT), len(hits),
             len({name.split('_')[0] for name in hits})))
    described = sum(1 for n in hits if hits[n][0][2])
    print('with a description from source:', described, '(%d%%)' % (100 * described // len(hits)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
