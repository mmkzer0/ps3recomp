#!/usr/bin/env python3
"""Emit the per-module glue for the call-level differential harness.

Input is what tools/lift_prx.py + tools/ppu_lifter.py already produced for ONE
firmware module (supplied by the user, kept OUTSIDE this repository):

    <name>_exports.json   {"base","toc","exports":{lib:{nid:opd_ea}}, ...}
    <name>_imports.json   {lib:{nid:stub_code_ea}}
    <name>_image.bin      relocated image (read only to decode the import stubs)

Output (written into --out, which must not be inside this repository):

    <prefix>harness_tables.cpp   exports, imports (with the stub's pointer-slot
                                 EA), base/TOC, the lifted function table
    <prefix>harness_layout.cpp   sizeof/offsetof of the lifted code's own
                                 ppu_context, checked against the runtime's

Nothing here is firmware, but the output is derived from firmware metadata, so
it is written next to the lifted C and never committed.

An SCE import stub is   li r12,0 ; oris r12,r12,HI ; lwz r12,LO(r12) ; ...
and the word it loads (the slot) points at the {code,toc} descriptor the module
loader fills in. The harness patches that slot, so the stub's own code runs
unchanged and the lifted caller cannot tell the import from a real one.
"""
import argparse, json, os, struct, sys

ROOT = os.path.realpath(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dh_symbols  # noqa: E402


def be32(buf, off):
    return struct.unpack(">I", buf[off:off + 4])[0]


def decode_slot(image, base, stub_ea):
    o = stub_ea - base
    if o < 0 or o + 12 > len(image):
        return 0
    i0, i1, i2 = be32(image, o), be32(image, o + 4), be32(image, o + 8)
    if i0 != 0x39800000 or (i1 >> 16) != 0x658C or (i2 >> 16) != 0x818C:
        return 0
    hi = i1 & 0xFFFF
    lo = i2 & 0xFFFF
    if lo & 0x8000:
        lo -= 0x10000
    return ((hi << 16) + lo) & 0xFFFFFFFF


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--name", required=True, help="module name, e.g. libsync2")
    ap.add_argument("--prefix", required=True, help="lifter --symbol-prefix, e.g. fwsync2_")
    ap.add_argument("--exports", required=True)
    ap.add_argument("--imports", required=True)
    ap.add_argument("--image", required=True)
    ap.add_argument("--header", required=True, help="the lifter's header name, e.g. fwsync2.h")
    ap.add_argument("--out", required=True)
    ap.add_argument("--names", help="optional JSON {nid_hex: name} consulted before the NID database")
    ap.add_argument("--symbols", help="override-symbol file (dh_symbols.py): named internal addresses, "
                                      "bound to the image by its SHA-256")
    ap.add_argument("--synthetic", action="store_true",
                    help="input is the checked-in synthetic fixture (not firmware): allow an "
                         "in-repository build directory")
    a = ap.parse_args()

    def inside_repo(p):
        p = os.path.realpath(p)
        return p == ROOT or p.startswith(ROOT + os.sep)

    if not a.synthetic:
        for label, p in (("--exports", a.exports), ("--imports", a.imports), ("--image", a.image)):
            if inside_repo(p):
                sys.exit(f"refusing firmware-derived input inside the repository ({label}): {os.path.realpath(p)}")
    out = os.path.realpath(a.out)
    if not a.synthetic and inside_repo(out):
        sys.exit("refusing to write firmware-derived output inside the repository: " + out)
    os.makedirs(out, exist_ok=True)

    ex = json.load(open(a.exports))
    im = json.load(open(a.imports))
    image = open(a.image, "rb").read()
    base = int(ex["base"], 16)
    toc = int(ex["toc"], 16)

    try:
        from nid_database import get_default_db
        db = get_default_db()
    except Exception:
        db = None
    names = {int(k, 16): v for k, v in json.load(open(a.names)).items()} if a.names else {}

    def nm(nid):
        if nid in names:
            return names[nid]
        if db:
            r = db.lookup_nid(nid)
            if r:
                return r[1]
        return ""

    lines = ["// GENERATED by tools/diff_harness/gen_tables.py -- derived from module metadata.",
             "// Do not commit. Lives next to the lifted C, outside the repository.",
             '#include "dh_module.h"', "",
             'extern "C" const prx_func_entry %sfunction_table[];' % a.prefix,
             'extern "C" const uint64_t %sfunction_table_count;' % a.prefix,
             'extern "C" const uint32_t %sctx_layout[];' % a.prefix, "",
             "static const dh_export k_exports[] = {"]
    n_ex = 0
    for lib, d in ex["exports"].items():
        for nid, opd in sorted(d.items()):
            n = int(nid, 16)
            lines.append('    {0x%08Xu, 0x%08Xu, "%s", "%s"},' % (n, int(opd, 16), lib, nm(n)))
            n_ex += 1
    lines += ["};", "", "static const dh_import k_imports[] = {"]
    n_im = 0
    bad = 0
    for lib, d in im.items():
        for nid, stub in sorted(d.items()):
            n = int(nid, 16)
            s = int(stub, 16)
            slot = decode_slot(image, base, s)
            if not slot:
                bad += 1
            lines.append('    {0x%08Xu, 0x%08Xu, 0x%08Xu, "%s", "%s"},' % (n, s, slot, lib, nm(n)))
            n_im += 1
    sym_rows, sym_sha = [], ""
    if a.symbols:
        if not a.synthetic and inside_repo(a.symbols):
            sys.exit(f"refusing firmware-derived input inside the repository (--symbols): {os.path.realpath(a.symbols)}")
        sym_sha, syms = dh_symbols.load(a.symbols, image, base)
        sym_rows = ['    {"%s", 0x%08Xu},' % (n, ea) for n, ea, _ in syms]
    lines += ["};", ""]
    if sym_rows:
        lines += ["static const dh_symbol k_symbols[] = {"] + sym_rows + ["};", ""]
    lines += ['extern "C" const dh_module dh_module_desc = {',
              '    "%s", 0x%08Xu, 0x%08Xu, "%s",' % (a.name, base, toc, os.path.realpath(a.image)),
              "    k_exports, %d, k_imports, %d," % (n_ex, n_im),
              "    %sfunction_table, %sfunction_table_count, %sctx_layout," % (a.prefix, a.prefix, a.prefix),
              "    %s, %d, \"%s\"" % ("k_symbols" if sym_rows else "nullptr", len(sym_rows), sym_sha),
              "};", ""]
    open(os.path.join(out, a.prefix + "harness_tables.cpp"), "w").write("\n".join(lines))

    lay = ["// GENERATED by tools/diff_harness/gen_tables.py. Do not commit.",
           "#include <stddef.h>", '#include "%s"' % a.header, "",
           'extern "C" const uint32_t %sctx_layout[] = {' % a.prefix,
           "    (uint32_t)sizeof(ppu_context), (uint32_t)offsetof(ppu_context, gpr), (uint32_t)offsetof(ppu_context, fpr),",
           "    (uint32_t)offsetof(ppu_context, cr), (uint32_t)offsetof(ppu_context, lr), (uint32_t)offsetof(ppu_context, ctr),",
           "    (uint32_t)offsetof(ppu_context, xer), (uint32_t)offsetof(ppu_context, thread_id),",
           "};", ""]
    open(os.path.join(out, a.prefix + "harness_layout.cpp"), "w").write("\n".join(lay))
    print("gen_tables: %s: %d exports, %d imports (%d without a decodable slot), base 0x%08X toc 0x%08X -> %s"
          % (a.name, n_ex, n_im, bad, base, toc, out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
