#!/usr/bin/env python3
"""Synthetic SPU jobs for test_spu_xdiff_poison.c (docs/SPU_LIFTER.md "Liveness", docs/SPU_XDIFF.md 8.2).

One caller and one callee at 0x40. The callee takes a 0x40-byte frame, spills a register into it, returns
a value in $r3 and leaves a scratch value in $r4. The caller reads $r3 after the call and signals it
through the outbound mailbox, then stops:

  ok         the caller reads nothing else: $r3 is the only live-out register, the frame is dead
  nested     the callee calls a second function at 0x80 and keeps its return address in a 0x20-byte frame while it
             does: two returns, the inner one with the outer one still open
  unbalanced the callee returns without giving its frame back: $r1 is not the entry value at the return

  frame      the caller reads the callee's frame after the call (the quadword the callee spilled $r5 into) and
             signals that instead of $r3: every register claim holds, a "dead frame" claim is false
  copy       the caller copies $r4, which the callee left behind, into $r10 and signals $r3: a claim that $r4
             is dead is false, and only the end state shows it

The claims the C test takes from this directory are what tools/spu_liveness.py says about each image; the
false ones are written in the test itself.

Usage: gen_xdiff_poison_job.py OUTDIR   -> xdiff_poison_job.h, xp_<variant>.bin, xp_<variant>.json
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools"))
import spu_liveness

CALLEE = 0x40
INNER = 0x80                   # the nested variant's second callee
FRAME = 0x40
NESTED_FRAME = 0x20
SPILL_QUAD = 2                 # the spill sits at 0x20($r1) after the prologue, 0x20 below the entry sp
OUT_MBOX = 28
STOP_CODE = 0x1234
# Not code addresses: the function finder reads a small immediate that is one as a continuation entry.
SENTINEL_R3, SENTINEL_R4, SPILL_VALUE = 0x3333, 0x4444, 0x5555


def word(v):
    return v & 0xFFFFFFFF


def ri10(op8, i10, ra, rt):
    return word((op8 << 24) | ((i10 & 0x3FF) << 14) | (ra << 7) | rt)


def ai(rt, ra, imm):
    return ri10(0x1C, imm, ra, rt)


def lqd(rt, ra, quad):
    return ri10(0x34, quad, ra, rt)


def stqd(rt, ra, quad):
    return ri10(0x24, quad, ra, rt)


def ori(rt, ra, imm):
    return ri10(0x04, imm, ra, rt)


def il(rt, imm16):
    return word((0x081 << 23) | ((imm16 & 0xFFFF) << 7) | rt)


def brsl(rt, pc, target):
    return word((0x66 << 23) | ((((target - pc) >> 2) & 0xFFFF) << 7) | rt)


def bi(ra):
    return word(0x1A8 << 21 | ra << 7)


def wrch(ch, rt):
    return word((0x10D << 21) | (ch << 7) | rt)


def stop(code):
    return word(code & 0x3FFF)


def caller(mode):
    w = [il(4, 0x7777), il(5, SPILL_VALUE)]
    w.append(brsl(0, 4 * len(w), CALLEE))
    if mode == "frame":
        w += [lqd(7, 1, -SPILL_QUAD), wrch(OUT_MBOX, 7)]   # the mailbox takes one write: nothing else is signalled
    else:
        if mode == "copy":
            w.append(ori(10, 4, 0))
        w.append(wrch(OUT_MBOX, 3))
    w.append(stop(STOP_CODE))
    return w


def callee(balanced):
    w = [ai(1, 1, -FRAME), stqd(5, 1, SPILL_QUAD), lqd(6, 1, SPILL_QUAD), il(3, SENTINEL_R3), il(4, SENTINEL_R4)]
    if balanced:
        w.append(ai(1, 1, FRAME))
    w.append(bi(0))
    return w


def nested_callee():
    return [ai(1, 1, -NESTED_FRAME), stqd(0, 1, 1), brsl(0, CALLEE + 8, INNER), lqd(0, 1, 1), ai(1, 1, NESTED_FRAME), bi(0)]


def nested_inner():
    return [il(3, SENTINEL_R3), il(5, SPILL_VALUE), bi(0)]


def image(mode, balanced):
    head = caller(mode)
    assert 4 * len(head) <= CALLEE
    nop = 0x201 << 21
    if mode == "nested":
        words = head + [nop] * ((CALLEE >> 2) - len(head)) + nested_callee()
        words += [nop] * ((INNER >> 2) - len(words)) + nested_inner()
    else:
        words = head + [nop] * ((CALLEE >> 2) - len(head)) + callee(balanced)   # nop padding up to the callee
    return b"".join(w.to_bytes(4, "big") for w in words)


VARIANTS = (("ok", "ok", True), ("frame", "frame", True), ("copy", "copy", True), ("nested", "nested", True),
            ("unbalanced", "ok", False))


def c_array(f, name, data):
    f.write(f"static const unsigned char {name}[{len(data)}u] = {{\n")
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",\n")
    f.write("};\n")


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "xdiff_poison_job.h"), "w", encoding="utf-8") as h:
        h.write("/* generated by gen_xdiff_poison_job.py */\n")
        h.write(f"#define XP_CALLEE 0x{CALLEE:X}u\n#define XP_INNER 0x{INNER:X}u\n#define XP_FRAME 0x{FRAME:X}u\n")
        h.write(f"#define XP_NESTED_FRAME 0x{NESTED_FRAME:X}u\n")
        h.write(f"#define XP_SPILL_BELOW_SP 0x{FRAME - 16 * SPILL_QUAD:X}u\n")
        h.write(f"#define XP_STOP_CODE 0x{STOP_CODE:X}u\n#define XP_OUT_MBOX {OUT_MBOX}u\n")
        h.write(f"#define XP_R3 0x{SENTINEL_R3:X}u\n#define XP_SPILL 0x{SPILL_VALUE:X}u\n")
        for name, mode, balanced in VARIANTS:
            data = image(mode, balanced)
            c_array(h, f"xp_{name}_code", data)
            with open(os.path.join(out, f"xp_{name}.bin"), "wb") as f:
                f.write(data)
            if spu_liveness.main([os.path.join(out, f"xp_{name}.bin"), "--base", "0", "--entry", "0",
                                  "-o", os.path.join(out, f"xp_{name}.json")]) != 0:
                raise SystemExit(f"spu_liveness failed on {name}")


if __name__ == "__main__":
    main()
