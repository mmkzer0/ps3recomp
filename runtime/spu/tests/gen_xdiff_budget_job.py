#!/usr/bin/env python3
"""Synthetic SPU loops without effects for test_spu_xdiff_budget.c (docs/SPU_XDIFF.md section 10).

usage: gen_xdiff_budget_job.py <outdir>

Writes <outdir>/xdiff_budget_job.elf, which build rules lift with
tools/spu_lifter.py, and <outdir>/xdiff_budget_job.h, which carries the same
bytes for the interpreter and every address the test checks. Hand-encoded
instructions only. Each job counts r3 down to zero and stops; none touches a
channel, so its transcript is empty and the only thing that can end it early is
the budget. The three jobs close their loop three different ways, one for each
kind of site the budgeted twin counts:

  A  0x000  one function: `ai r3,r3,-1 ; brnz r3,A` -- a backward goto
  B  0x100  two functions: `br B1`, `brnz r3,B0` -- cross-function transfers
  C  0x200  `ila r5,C1`; at C1 `ai ; binz r3,r5` -- an indirect branch, which
            must resolve to the twin's own copy of C1 to stay counted

r3 starts as the test sets it; started at 0 each job counts through 2^32 laps,
which is a run no test waits for unless the budget ends it.
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "tools"))
from wrap_spu_elf import wrap

A_ENTRY, B_ENTRY, B1_ENTRY, C_ENTRY, C1_ENTRY = 0x000, 0x100, 0x108, 0x200, 0x208
A_STOP, B_STOP, C_STOP = 0x11, 0x12, 0x13
LS_END = 0x400


def word(v):
    return v & 0xFFFFFFFF


def ai(rt, ra, imm10):
    return word((0x1C << 24) | ((imm10 & 0x3FF) << 14) | (ra << 7) | rt)


def il(rt, imm16):
    return word((0x081 << 23) | ((imm16 & 0xFFFF) << 7) | rt)


def ila(rt, imm18):
    return word((0x21 << 25) | ((imm18 & 0x3FFFF) << 7) | rt)


def br(word_off):
    return word((0x64 << 23) | ((word_off & 0xFFFF) << 7))


def brnz(rt, word_off):
    return word((0x42 << 23) | ((word_off & 0xFFFF) << 7) | rt)


def binz(rt, ra):
    return word((0x129 << 21) | (ra << 7) | rt)


def stop(code):
    return word(code & 0x3FFF)


def jobs():
    """(entry address, words, symbol name) for every function of the image."""
    return [
        (A_ENTRY, [ai(3, 3, -1), brnz(3, -1), stop(A_STOP)], "xb_a"),
        (B_ENTRY, [ai(3, 3, -1), br(1)], "xb_b0"),
        (B1_ENTRY, [brnz(3, -2), stop(B_STOP)], "xb_b1"),
        (C_ENTRY, [ila(5, C1_ENTRY), il(60, 0)], "xb_c0"),
        (C1_ENTRY, [ai(3, 3, -1), binz(3, 5), stop(C_STOP)], "xb_c1"),
    ]


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    code = bytearray(LS_END)
    symbols = []
    for addr, words, name in jobs():
        for i, v in enumerate(words):
            struct.pack_into(">I", code, addr + 4 * i, v)
        symbols.append({"name": name, "addr": addr, "size": 4 * len(words)})
    with open(os.path.join(out, "xdiff_budget_job.elf"), "wb") as f:
        f.write(wrap(bytes(code), base=0, entry=A_ENTRY, symbols=symbols))
    with open(os.path.join(out, "xdiff_budget_job.h"), "w") as f:
        f.write("/* Generated by gen_xdiff_budget_job.py -- do not edit. */\n#pragma once\n")
        consts = (("A_ENTRY", A_ENTRY), ("B_ENTRY", B_ENTRY), ("C_ENTRY", C_ENTRY),
                  ("A_STOP", A_STOP), ("B_STOP", B_STOP), ("C_STOP", C_STOP))
        f.writelines(f"#define XB_{name} 0x{value:X}u\n" for name, value in consts)
        f.write(f"#define XB_CODE_BYTES {len(code)}u\n")
        f.write("static const unsigned char xb_code[XB_CODE_BYTES] = {\n")
        for i in range(0, len(code), 16):
            f.write("  " + ",".join(f"0x{b:02X}" for b in code[i:i + 16]) + ",\n")
        f.write("};\n")


if __name__ == "__main__":
    main()
